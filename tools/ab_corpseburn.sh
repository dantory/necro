#!/bin/bash
# ★ 긴 측정은 저절로 떨어져 나간다(600초 상한에 잘리지 않게) — tools/ab_guard.sh
. "$(dirname "$0")/ab_guard.sh"
# ══ D-31 · **네 번째 갈래 — 관문이 «바닥의 시체»를 태운다** (battle.js __CORPSEBURN) ══
#
#   D-29(마나) 와 D-30(쿨) 이 둘 다 ✗ 로 닫으면서 **같은 답**을 남겼다:
#   **저절로 다시 차는 것을 물어서는 뒤에 사건이 안 선다.**
#     · 마나 — `MANA_WALL`(초당 되살리기 0.75몫)이 늘 채워 놓는다. 뒤 막힘마나% 가 **0·0·0**
#       이라 태워도 다음 소환 전에 다시 찬다(그래서 D-29 는 앞으로 샜다).
#     · 쿨   — 잠그면 **시도가 늘어** 되세운 몫이 되레 늘었다(세움/분 147 → 167).
#       막힘쿨% 만 보면 「무는 것」처럼 보였다 — 비율에 속을 뻔한 자리다.
#
#   ☞ 남은 축은 **저절로 안 차는 것 — «시체»** 다. 지금 뒤 세 칸의 막힘시체% 는 **0 · 0 · 0**
#     이고 못은 상한(140) 언저리에 붙어 있다 — 재료가 사실상 무한이다.
#     관문 수법(pool·curse·charge·add)이 터질 때 **바닥에 쌓인 시체의 `__CORPSEBURN` 비율**
#     을 태운다. 무너진 뒤 되세울 «재료»가 없으면 같은 무너짐이 실제로 오래 남는다.
#   ★ **잃음 총량은 한 톨도 안 늘린다** — 소환수는 하나도 안 깎는다(D-26 ④ 가 막는 자리).
#     태우는 것은 **이미 죽어 바닥에 누운 것**뿐이다.
#   ★ **절규(howl)에는 안 붙인다** — 잃음의 94%가 이미 거기 걸려 있다.
#     ⚠ **그 94% 는 근접을 통째로 버린 자가 낸 수다**(D-49 · 2026-08-23) — 실제로는 절규 72% · 근접 24.5%.
#   ★ 기본값은 재기 전까지 **한 톨도 안 바꾼다**(__CORPSEBURN = 0 · 문만 나 있다).
#
#   판정 (재기 전에 적는다 · 견줄 팔은 이미 디스크에 있다: tmp/d27_rare.log · 같은 씨앗 열둘)
#     ① **손잡이가 도는가** — 9분 자의 「그 한 방에 못 바닥남(<3)」이 **25% 위로.**
#        0 이면 태우기는 하되 **재료를 못 끊은 것**이다([[knob-that-does-nothing]]).
#     ② **재료가 실제로 얕아지는가 — «비율» 이 아니라 «몫» 으로 본다.**
#        ★★ 여기가 D-30 이 진 자리다([[threshold-and-ruler-must-match]]) — 막힘시체% 는
#          분모(시도)가 늘면 같이 오르므로 **판정에 안 쓴다.**
#        · 「못」 줄의 뒤 세 칸(21-40 · 41-60 · 61+)이 A 팔보다 **셋 다 내려가고**,
#          적어도 한 칸이 **상한의 절반(70) 아래**로 내려온다.
#        · 그리고 **세움/분** 이 뒤 세 칸에서 A 팔(96 / 134 / 147)보다 **셋 다 내려간다.**
#          이것이 「되세운 몫이 실제로 줄었다」의 유일한 증거다(D-30 은 여기서 늘었다).
#     ③ **사건이 «커져야» 한다 — 수가 아니라 «무너져 있는 시간»이다.**
#        · 뒤 **회복초중앙**이 A 팔(10.4 / 13.3 / 9.1)보다 **셋 다 오른다.**
#        · 그러면서 뒤(층 21+) 무너짐 판당이 **17.5 아래로 안 내려간다**(A 팔 21.83 의 80%).
#          그 아래면 사건이 «상태»로 굳은 것이다(D-27 B 팔이 그렇게 졌다).
#     ④ **끝이 되면 안 된다** — 회복초중앙이 A 팔의 **두 배 아래**(20.8 / 26.6 / 18.2)이고
#        「안 돌아옴」이 뒤 무너짐의 **5% 아래**(A 팔 2/262 = 0.8%).
#        그리고 군세/상한이 뒤 세 칸 다 **0.45 위**(A 팔 0.57 / 0.60 / 0.64).
#     ⑤ **앞 6분이 안 물러야 한다** — 앞 6분 죽음이 A 팔(4.33)의 ±20% 안(3.46~5.20).
#        ★ D-29 가 정확히 여기서 졌다 — 뒤를 노린 손잡이가 앞으로 샜다.
#        ★ 이 갈래는 **특히 앞이 위험하다**: 앞에서는 못이 원래 얕다(1-10 칸). 앞 6분이
#          물러나면 값을 낮추기 전에 **「깊이에 따라 켜지는」 형태**를 먼저 생각할 것.
#     ⑥ **쉬워지지도 어려워지지도 않는다** — 20분 최고층이 A 팔(61.58)의 −10%(55.4) 위이고
#        D-24 기준(66.5)의 115%(76.5) 아래.
#   ①~⑥ 을 다 세운 팔이 있으면 그 값을 기본값으로 옮긴다. 없으면 **안 켠다** — 그리고
#   「재료를 끊어도 뒤에 갈래가 안 선다」를 수와 함께 적는다. 그러면 D 의 답은
#   「무너짐을 «되세우는 쪽»에서 만들 수 없다」로 굳고, 남는 길은 **잃음 갈래를 늘리는 것**
#   (지금 94%가 절규 하나)뿐이다.
#
#   ★ 사다리부터 (9분 × 씨앗 셋) — 태움이 값을 따라 오르는지, 그리고 「바닥남」이 같이
#     오는지를 먼저 본다. 관문은 5층마다 서므로 9분이면 넉넉히 여러 번 터진다
#     ([[floor-far-from-threshold]] — 바닥이 0 인 자로는 못 잰다).
set -u
REPO=/Users/lbs/source/personal/necro
cd "$REPO" || exit 1
MIN=${MIN:-20}
SEEDS=${SEEDS:-"1,3,7,9,11,13,2,4,6,8,10,12"}   # d27_rare / d24_base 와 **같은 판**

node tools/chrome_guard.mjs 2>&1 | tail -2

# ── 0) 태움이 값을 따라 오르는가 (9분 × 씨앗 셋) ───────────────────────────
echo "═════ 0) 사다리 · 9분 × 씨앗 13,1,3 · $(date +%H:%M) ═════"
for b in 0 0.3 0.5 0.8; do
  OUT="tmp/d31_lad_${b}.log"
  [ -s "$OUT" ] && { echo "== $OUT 이미 있음 · 건너뜀 =="; continue; }
  NECRO_KNOBS="__CORPSEBURN=$b" node tools/start_probe.mjs 9 "13,1,3" > "$OUT" 2>&1
  echo "── CORPSEBURN=$b ──"
  grep '시체태움(D-31)' "$OUT" || echo "  (시체태움 줄 없음 — 손잡이가 0 이거나 관문이 안 터졌다)"
  grep -A 7 '뒤에서 왜 자리를 못 채우나' "$OUT"
  grep '못(D-31' "$OUT"
done

# ── 0b) **판이 한 톨도 안 바뀌었는지** — 손잡이 0 은 옛 판과 «바이트까지» 같아야 한다.
#   d30_lad_0.log 는 같은 자(9분 × 씨앗 13,1,3)를 **이 수정 전에** 찍은 것이다.
#   D-31 이 새로 내는 줄 둘(시체태움 · 못)만 빼고 견준다.
echo "── 0b) 문만 낸 것이 맞는가 (d31_lad_0 ↔ d30_lad_0) ──"
if [ -s tmp/d30_lad_0.log ] && [ -s tmp/d31_lad_0.log ]; then
  if diff -q <(grep -v '시체태움\|못(D-31' tmp/d31_lad_0.log) tmp/d30_lad_0.log >/dev/null; then
    echo "  ✔ 바이트까지 같다 — 기본값에서 판이 한 톨도 안 바뀌었다"
  else
    echo "  ✘ 갈렸다 — 아래 차이를 먼저 볼 것"; diff <(grep -v '시체태움\|못(D-31' tmp/d31_lad_0.log) tmp/d30_lad_0.log | head -20
  fi
else echo "  (견줄 로그가 없다)"; fi

# ── 1) 두 팔 (20분 × 씨앗 열둘) ────────────────────────────────────────────
for b in 0.5 0.8; do
  OUT="tmp/d31_c${b}.log"
  [ -s "$OUT" ] && { echo "== $OUT 이미 있음 · 건너뜀 =="; continue; }
  echo "═════ CORPSEBURN=$b → $OUT · $(date +%H:%M) ═════"
  NECRO_KNOBS="__CORPSEBURN=$b" node tools/start_probe.mjs "$MIN" "$SEEDS" > "$OUT" 2>&1
  echo "== $b 끝 · $(date +%H:%M:%S) ==" >&2
done

# ── 2) 견줌 ────────────────────────────────────────────────────────────────
sum () {   # $1 = 로그
  local f="$1"
  grep -A 8 '군대가 무너지는 사건' "$f"
  grep -A 7 '뒤에서 왜 자리를 못 채우나' "$f"
  grep '못(D-31' "$f"
  grep '시체태움(D-31)' "$f"
  awk '$1=="360"  {print "  앞 6분 죽음(평균) : " $NF}' "$f"
  awk '$1=="1200" {print "  20분 최고층(평균) : " $2}'  "$f"
}
echo ""
echo "═════ 견줄 팔(D-27 A 「드묾」 · 지금 켜져 있는 것) : tmp/d27_rare.log ═════"
sum tmp/d27_rare.log
for b in 0.5 0.8; do
  echo ""; echo "═════ CORPSEBURN=$b (tmp/d31_c${b}.log) ═════"
  sum "tmp/d31_c${b}.log"
  grep -A 10 '무엇이 소환수를 죽였나' "tmp/d31_c${b}.log"
done
