#!/bin/bash
# ★ 긴 측정은 저절로 떨어져 나간다(600초 상한에 잘리지 않게) — tools/ab_guard.sh
. "$(dirname "$0")/ab_guard.sh"
# ══ D-32 · **다섯째 갈래 — 관문이 «지금 서 있는 군세»를 직접 무너뜨린다** (battle.js __GATEBLAST) ══
#
#   D-29(마나)·D-30(쿨)·D-31(시체) 셋이 **같은 이유로** ✗ 로 닫혔다:
#   **무엇을 태우든 잃음/분이 100 을 넘는 판에서는 재료도 손도 곧바로 다시 찬다.**
#   그리고 셋 다 **뒤보다 앞을 먼저 물었다** — 뒤에는 여유가 쌓여 있고 앞에는 없기 때문이다.
#   ☞ 그래서 「되세우기를 조이는 갈래」는 D-31 에서 통째로 닫았다.
#
#   ☞ 남은 길은 **«잃음 갈래를 늘리는 것»** 하나다. D-31 표에서도 막타가
#     **절규 58% · 근접 36%**, 깎은몫은 **절규 91%** — 잃음이 사실상 한 갈래다.
#     갈래가 하나뿐이면 그 하나가 만든 «평형»이 곧 판이고(D-26 이 낸 답),
#     무너짐은 «사건»이 아니라 «상태»로 굳는다.
#   ☞ 그래서 관문 수법(pool·curse·charge·add)이 터질 때 **그 자리(네크로 발밑) 둘레
#     190 안의 소환수만** `floorHp × __GATEBLAST` 만큼 한 번에 문다(cause "blast").
#   ★ **절규(howl)에는 안 붙인다** — 거기 얹으면 갈래가 또 하나가 아니라 같은 하나다.
#   ★ **잦기가 아니라 크기다** — 관문 수법은 한 판에 수십 번만 터진다(D-31 실측 4분에 8번).
#     사건이 서려면 드물고 커야 한다(D-27 이 같은 답을 냈다).
#   ★ **이 갈래는 앞선 넷과 달리 잃음 «총량»을 늘린다** — 그것이 노림이다. 대신
#     **D-26 ④ 가 여기서 판을 본다**: 늘린 만큼 그냥 어려워지기만 하면(최고층이 뚝 떨어지면)
#     진 것이다(⑥).
#   ★ 기본값은 재기 전까지 **한 톨도 안 바꾼다**(__GATEBLAST = 0 · 문만 나 있다).
#
#   판정 (재기 전에 적는다 · 견줄 팔은 이미 디스크에 있다: tmp/d27_rare.log · 같은 씨앗 열둘)
#     ① **손잡이가 도는가 — 갈래가 «둘»이 되는가.** 「무엇이 소환수를 죽였나」에서
#        **blast 막타% 가 25 위**(지금 절규 58 · 근접 36 · 나머지 다 합쳐 6).
#        · 「한 번에 문 마리」가 0 이면 → 반경 안에 아무도 없다(터지는 자리가 틀렸다)
#        · 「죽인 수」가 0 이면      → 이빨이 없다(값이 소환수 체력에 진다)
#        둘은 고칠 자리가 전혀 다르다([[knob-that-does-nothing]]).
#     ② **사건이 «커져야» 한다 — 수가 아니라 «무너져 있는 시간»이다.**
#        뒤 **회복초중앙**이 A 팔(10.4 / 13.3 / 9.1)보다 **셋 다 오른다.**
#     ③ **그러면서 «상태»로 굳으면 안 된다** — 뒤(층 21+) 무너짐 판당이
#        **17.5 아래로 안 내려간다**(A 팔 21.83 의 80%). 그 아래면 늘 무너져 있는 것이다
#        (D-27 B 팔이 그렇게 졌다).
#     ④ **끝이 되면 안 된다** — 회복초중앙이 A 팔의 **두 배 아래**(20.8 / 26.6 / 18.2)이고
#        「안 돌아옴」이 뒤 무너짐의 **5% 아래**(A 팔 0.8%).
#        그리고 군세/상한이 뒤 세 칸 다 **0.45 위**(A 팔 0.57 / 0.60 / 0.64).
#     ⑤ **앞 6분이 안 물러야 한다** — 앞 6분 죽음이 A 팔(4.33)의 ±20% 안(3.46~5.20).
#        ★ D-29 · D-31 이 정확히 여기서 졌다 — 뒤를 노린 손잡이가 앞으로 샜다.
#        ★ 이 갈래는 **앞이 덜 위험하다**(관문이 층 5 부터라 앞에는 터짐이 적다) — 그래도 본다.
#     ⑥ **쉬워지지도 어려워지지도 않는다** — 20분 최고층이 A 팔(61.58)의 −10%(55.4) 위이고
#        D-24 기준(66.5)의 115%(76.5) 아래. **잃음을 늘리는 갈래라 여기가 제일 위험하다.**
#   ①~⑥ 을 다 세운 팔이 있으면 그 값을 기본값으로 옮긴다. 없으면 **안 켠다** — 그리고
#   「잃음 갈래를 늘려도 뒤에 사건이 안 선다」를 수와 함께 적는다.
#
REPO="/Users/lbs/source/personal/necro"
cd "$REPO" || exit 1
MIN=${MIN:-20}
SEEDS=${SEEDS:-"1,3,7,9,11,13,2,4,6,8,10,12"}   # d27_rare / d24_base 와 **같은 판**

node tools/chrome_guard.mjs 2>&1 | tail -2

# ── 0) 무는 몫이 값을 따라 오르는가 (9분 × 씨앗 셋) ────────────────────────
echo "═════ 0) 사다리 · 9분 × 씨앗 13,1,3 · $(date +%H:%M) ═════"
for b in 0 0.5 1.0; do
  OUT="tmp/d32_lad_${b}.log"
  [ -s "$OUT" ] && { echo "== $OUT 이미 있음 · 건너뜀 =="; continue; }
  NECRO_KNOBS="__GATEBLAST=$b" node tools/start_probe.mjs 9 "13,1,3" > "$OUT" 2>&1
  echo "── GATEBLAST=$b ──"
  grep '관문폭발(D-32)' "$OUT" || echo "  (관문폭발 줄 없음 — 손잡이가 0 이거나 관문이 안 터졌다)"
  grep -A 11 '무엇이 소환수를 죽였나' "$OUT"
done

# ── 0b) **판이 한 톨도 안 바뀌었는지** — 손잡이 0 은 옛 판과 «바이트까지» 같아야 한다.
#   d31_lad_0.log 는 같은 자(9분 × 씨앗 13,1,3)를 **이 수정 전에** 찍은 것이다.
#   D-32 가 새로 내는 것 둘(관문폭발 줄 · 갈래표의 blast 칸)만 빼고 견준다.
echo "── 0b) 문만 낸 것이 맞는가 (d32_lad_0 ↔ d31_lad_0) ──"
if [ -s tmp/d31_lad_0.log ] && [ -s tmp/d32_lad_0.log ]; then
  if diff -q <(grep -v '관문폭발\|blast' tmp/d32_lad_0.log) <(grep -v '관문폭발\|blast' tmp/d31_lad_0.log) >/dev/null; then
    echo "  ✔ 바이트까지 같다 — 기본값에서 판이 한 톨도 안 바뀌었다"
  else
    echo "  ✘ 갈렸다 — 아래 차이를 먼저 볼 것"
    diff <(grep -v '관문폭발\|blast' tmp/d32_lad_0.log) <(grep -v '관문폭발\|blast' tmp/d31_lad_0.log) | head -20
  fi
else echo "  (견줄 로그가 없다)"; fi

# ── 1) 두 팔 (20분 × 씨앗 열둘) ────────────────────────────────────────────
for b in 0.5 1.0; do
  OUT="tmp/d32_g${b}.log"
  [ -s "$OUT" ] && { echo "== $OUT 이미 있음 · 건너뜀 =="; continue; }
  echo "═════ GATEBLAST=$b → $OUT · $(date +%H:%M) ═════"
  NECRO_KNOBS="__GATEBLAST=$b" node tools/start_probe.mjs "$MIN" "$SEEDS" > "$OUT" 2>&1
  echo "== $b 끝 · $(date +%H:%M:%S) ==" >&2
done

# ── 2) 견줌 ────────────────────────────────────────────────────────────────
sum () {   # $1 = 로그
  local f="$1"
  grep -A 8 '군대가 무너지는 사건' "$f"
  grep -A 7 '뒤에서 왜 자리를 못 채우나' "$f"
  grep '관문폭발(D-32)' "$f"
  awk '$1=="360"  {print "  앞 6분 죽음(평균) : " $NF}' "$f"
  awk '$1=="1200" {print "  20분 최고층(평균) : " $2}'  "$f"
}
echo ""
echo "═════ 견줄 팔(D-27 A 「드묾」 · 지금 켜져 있는 것) : tmp/d27_rare.log ═════"
sum tmp/d27_rare.log
grep -A 10 '무엇이 소환수를 죽였나' tmp/d27_rare.log
for b in 0.5 1.0; do
  echo ""; echo "═════ GATEBLAST=$b (tmp/d32_g${b}.log) ═════"
  sum "tmp/d32_g${b}.log"
  grep -A 11 '무엇이 소환수를 죽였나' "tmp/d32_g${b}.log"
done
