#!/bin/bash
# ★ 긴 측정은 저절로 떨어져 나간다(600초 상한에 잘리지 않게) — tools/ab_guard.sh
. "$(dirname "$0")/ab_guard.sh"
# ══ D-34 · **자를 먼저 고친다 — 「무너짐」의 분모를 손잡이에서 떼어 낸다** ══
#
#   D-33 이 남긴 ⓑ 다. 상한을 옮기는 손잡이(__TOUGH)를 켜자 옛 자가 「뒤 무너짐 판당
#   21.83 → 0.08」 이라고 말했는데, 같은 판에서 **군세/상한이 0.57~0.64 → 0.89~1.07** 로
#   올라갔다 — 문턱(0.70→0.35)을 아예 안 건드린 것이다. **손잡이가 분모를 옮기면
#   자가 눈을 감는다**([[threshold-and-ruler-must-match]] · [[floor-far-from-threshold]]).
#   지금 A 팔의 판정도 그 자 위에 서 있으니, 다음 갈래(상한을 사건 중에 흔드는 ⓐ)를
#   재기 **전에** 자부터 고친다.
#
#   새 자 = `start_probe.mjs` 의 「군대가 무너지는 사건 · 절대 자」
#     기준  = **최근 30초 동안 실제로 서 있던 최댓값**(관측값 · 손잡이가 못 옮긴다)
#     무너짐 = 그 최고가 4마리 이상인데 **절반 이하로** 꺼진 순간
#     회복   = 다시 그 최고에 닿기까지 · 죽음으로 끊기면 −1
#   ★ 옛 자는 그대로 둔 채 **나란히** 찍는다 — 안 그러면 D-23~33 과 못 견준다.
#
#   판정 (재기 전에 적는다)
#     ㉠ **A 팔에서 두 자가 같은 말을 하는가** — 뒤 세 칸 판당이 같은 자릿수여야 한다.
#        크게 어긋나면 새 자는 «다른 사건»을 세는 것이라 옛 표와 못 잇는다.
#     ㉡ **t=2 팔에서 새 자가 눈을 뜨고 있는가** — 옛 자는 0.08 로 죽는데 새 자가
#        뒤 판당 **0.5 이상**이면 자가 고쳐진 것이다.
#        · 새 자도 0 에 가까우면 → **판이 정말로 안 무너진 것**이고, D-33 의 결론은
#          자 탓이 아니었다는 뜻이다(그 또한 알아야 할 답이다 — 그러면 ⓐ 로 간다).
#     ㉢ **최고평균이 두 팔에서 갈리는가** — A 는 10 언저리, t=2 는 7 아래여야 한다.
#        기준이 관측값을 따라간다는 증거다. 두 팔이 같으면 기준이 안 움직이는 것이니
#        30초 창이 너무 길다는 뜻이다([[knob-that-does-nothing]]).
#
#   ★ 판은 **한 글자도 안 건드린다** — 이번 커밋은 자만 고친다.
set -u
cd /Users/lbs/source/personal/necro
MIN=${MIN:-9}; SEEDS=${SEEDS:-1,3,7}
node tools/chrome_guard.mjs || true

for arm in A T2; do
  OUT="tmp/d34_${arm}.log"
  [ -s "$OUT" ] && { echo "== $OUT 이미 있음 · 건너뜀 =="; continue; }
  echo "═════ $arm → $OUT · $(date +%H:%M:%S) ═════"
  if [ "$arm" = "A" ]; then K=""; else K="__TOUGH=2"; fi
  NECRO_KNOBS="$K" node tools/start_probe.mjs "$MIN" "$SEEDS" > "$OUT" 2>&1
  echo "== $arm 끝 · $(date +%H:%M:%S) ==" >&2
done

for arm in A T2; do
  echo ""; echo "═════ $arm (tmp/d34_${arm}.log) ═════"
  grep -A 8 '군대가 무너지는 사건 (' "tmp/d34_${arm}.log"
  grep -A 8 '절대 자' "tmp/d34_${arm}.log"
  grep -A 7 '뒤에서 왜 자리를 못 채우나' "tmp/d34_${arm}.log"
done
