## 이미 찾아 둔 원인 자리 (다시 안 찾아도 된다)
`hs/main.js` 의 `killEnemy()` 안:
```
  G.xp += m.elite ? 40 : 10;
  if (G.xp >= G.player.level * 500) { G.player.level++; ... }
```
셋이 문제다:
· ㉠ **문턱이 `level * 500` 누적 선형** — 한 레벨 값이 평생 500 으로 고정이라 **영원히 안 느려진다.**
   D2 는 레벨이 오를수록 요구치가 초선형으로 는다.
· ㉡ **처치 XP 가 층과 무관하게 10/40 고정** — 깊이 내려가는 보람이 XP 에 전혀 없다.
· ㉢ `if` 한 번이라 한 처치에 한 레벨만 오른다(곡선을 고치면 이건 오히려 맞는 쪽이니 확인만 해라).
   `hs/hud.css`/`main.js` 의 xp 바(`G.xp % 500`, `/5` 로 %)도 **500 고정을 전제**한다 — 곡선을 바꾸면
   **바가 반드시 같이 틀린다.** 바는 「이번 레벨 안에서의 진척」을 정확히 보여야 한다.

