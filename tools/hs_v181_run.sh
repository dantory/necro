### 1) loot.js — 옵션을 굴린다
- 슬롯 일곱: weapon / helm / armor / gloves / boots / ring / amulet.
  각 슬롯마다 어울리는 NOUN 목록을 둬라(반지에 Robe 가 나오면 안 된다).
- 레어도별 옵션 개수: 평범 0 · 매직 1~2 · 레어 3~4 · 유니크는 고정 규칙 + 옵션 2~3.
- 실제로 붙는 옵션(값 범위를 두고 굴려라, 층수 floor 가 값을 키운다):
  피해 +N% · 공격 속도 +N% · 최대 생명 +N · 소환수 피해 +N% · 금 획득 +N% ·
  이동 속도 +N% · 시체 폭발 범위 +N%.
- 각 옵션은 { key, label, value } 로 두고, **합산 함수** `sumAffixes(items)` 를 export 해라.
- 유니크 넷(UNIQUES)은 지금의 규칙 바꾸기(doubleNova/moreSkel/goldRush/splitSpear)를 그대로 유지.

