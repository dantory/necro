#!/bin/bash
# ★ 긴 측정은 저절로 떨어져 나간다(600초 상한에 잘리지 않게) — tools/ab_guard.sh
. "$(dirname "$0")/ab_guard.sh"
# ══ D-35 · **무너진 «직후» 상한이 내려앉는 문** ══ (`__CAPCRUSH` · 기본 0)
#
#   D-34 가 남긴 ⓐ 다. 그 전까지 다섯 갈래가 전부 졌다 —
#     D-29 마나 · D-30 쿨 · D-31 시체 · D-32 관문폭발 · D-33 회전율.
#   다섯 다 같은 모양으로 졌다: **무엇을 태우든 무엇을 물든 되세움이 그만큼 따라 올랐다.**
#   그리고 다섯 다 «잃는 쪽»을 건드렸다.
#   ☞ 이번에 미는 것은 **되세울 «자리» 자체**다. 무너진 순간 상한이 8초 동안 내려앉고
#     스르르 풀린다. 자원은 한 톨도 안 건드린다 — **자리는 저절로 다시 차지 않는다**
#     (D-29·D-31 이 「저절로 차는 것을 물었다」로 진 자리를 비켜 간다).
#
#   방아쇠는 **D-34 절대 자와 글자 그대로 같다** — 최근 30초 관측 최댓값 hi · hi ≥ 4 ·
#   서 있는 수 × 2 ≤ hi · 그리고 **한 사건에 한 번**(그 최고에 다시 닿기 전엔 안 문다).
#   자가 세는 그 사건에 문이 붙어 있어야 「사건 하나에 무슨 일이 났나」를 견줄 수 있다.
#
#   ★ 판정은 **새 자(절대 자) 칸으로만** 읽는다 — 이 문이 상한을 내리므로 옛 자
#     (군세/상한)는 D-33 과 똑같이 분모가 같이 내려가 **눈을 감는다**
#     ([[threshold-and-ruler-must-match]]).
#
#   끝 조건 (재기 전에 적는다 · 두 팔: A = 끔 · C5 = __CAPCRUSH=0.5)
#     ① **문이 실제로 도는가** — 「상한눌림(D-35)」 줄의 눌림 횟수가 0 이 아니고
#        판당 눌린 초가 20초 이상. 0 이면 방아쇠가 안 걸린 것이다([[knob-that-does-nothing]]).
#     ② **뒤에 «사건»이 서는가(이것이 D 의 물음이다)** — 새 자 뒤(층 21+) 판당이
#        A 팔 0.33 대비 **1.0 이상**(3배). 이 문의 존재 이유다.
#     ③ **회복이 «시간»을 갖는가** — 뒤 칸 회복초중앙이 A 팔보다 **길어야** 한다.
#        같거나 짧으면 눌러도 곧바로 되차는 것이라 D-29~33 과 같은 패배다.
#     ④ **앞을 더 세게 만들지 않았는가** — 앞(층 1-20) 판당 무너짐이 A 팔의 1.5배 이내,
#        그리고 **죽음 수가 A 팔의 1.3배 이내.** D-29·D-31·D-32 가 진 자리가 늘 여기였다
#        (뒤를 노린 손잡이가 앞을 물어 「그냥 어려워짐」이 된다 · D-26 ④).
#     ⑤ **판이 더 얕아지지 않았는가** — 최고층이 A 팔의 85% 이상. 그 아래면 난이도를
#        되잡은 것이 아니라 판을 짧게 만든 것이다.
#   ★ ②③ 이 통과하고 ④⑤ 가 살아 있을 때만 기본값을 켠다. 하나라도 어긋나면 ☒ 로 닫고
#     무엇이 어떻게 졌는지를 ROADMAP 에 적는다 — **진 것도 답이다**(D-29~33 이 그랬다).
set -u
cd /Users/lbs/source/personal/necro
MIN=${MIN:-9}; SEEDS=${SEEDS:-1,3,7}
node tools/chrome_guard.mjs || true

for arm in A C5; do
  OUT="tmp/d35_${arm}.log"
  [ -s "$OUT" ] && { echo "== $OUT 이미 있음 · 건너뜀 =="; continue; }
  echo "═════ $arm → $OUT · $(date +%H:%M:%S) ═════"
  if [ "$arm" = "A" ]; then K=""; else K="__CAPCRUSH=0.5"; fi
  NECRO_KNOBS="$K" node tools/start_probe.mjs "$MIN" "$SEEDS" > "$OUT" 2>&1
  echo "== $arm 끝 · $(date +%H:%M:%S) ==" >&2
done

for arm in A C5; do
  echo ""; echo "═════ $arm (tmp/d35_${arm}.log) ═════"
  grep -A 8 '절대 자' "tmp/d35_${arm}.log"
  grep    '상한눌림(D-35)' "tmp/d35_${arm}.log"
  grep -A 3 '최고층' "tmp/d35_${arm}.log" | head -8
  grep    '죽음' "tmp/d35_${arm}.log" | head -3
done
