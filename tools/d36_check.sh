#!/bin/bash
# ★ 긴 측정은 저절로 떨어져 나간다(600초 상한에 잘리지 않게) — tools/ab_guard.sh
. "$(dirname "$0")/ab_guard.sh"
# ══ D-36 · **방아쇠를 «사건» 이 아니라 «층» 에 건다** ══ (`__DEEPCAP` · 기본 0)
#
#   여섯 갈래가 다 졌다 — D-29 마나 · D-30 쿨 · D-31 시체 · D-32 관문폭발 ·
#   D-33 회전율 · D-35 자리. 그런데 **여섯이 여섯 이유로 진 게 아니다**:
#   여섯 다 방아쇠가 「무너지면 벌한다」였고, 무너짐은 A 팔에서 **앞 70 : 뒤 9**
#   (88%가 20층 앞)로 터진다. 무엇을 벌하든 **열에 아홉을 앞에서 쓴다.**
#   D-35 가 ④⑤ 로 진 까닭이 그것이다(죽음 12 → 17 · 최고층 83.1%).
#   ☞ 그래서 미는 것(자리)은 그대로 두고 **거는 자리만** 옮긴다. 층 21 아래에서는
#     문이 **한 번도 안 걸린다** — 앞을 세게 만드는 길이 «수»가 아니라 «꼴»로 막힌다.
#   ☞ 자리를 고른 까닭: 여섯 중 회복초중앙을 실제로 늘린 축은 D-35 하나뿐이었다
#     (18.2 → 38.4 · 2.1배). **읽음은 맞았고 방아쇠만 틀렸다.**
#
#   끝 조건 (재기 전에 적는다 · 두 팔: A = 끔 · D5 = __DEEPCAP=0.5 · 9분 × 씨앗 1·3·7)
#     ★ 견줄 A 팔은 **D-34·D-35 의 A 팔과 같은 수**다(씨앗이 같으면 판이 똑같이 구른다):
#       앞 판당 23.33 · **뒤 판당 3.00** · 뒤 회복초중앙 18.2 · 죽음 합 12 · 9분 최고층 29.67.
#       ※ D-35 의 ② 는 **D-34 의 T2 팔 값(0.33)을 A 팔인 줄 알고** 문턱에 박았다가 틀렸다.
#         이번 문턱은 위 A 팔 수에서만 뽑는다([[threshold-and-ruler-must-match]]).
#     ① **문이 실제로 도는가** — 「깊이눌림(D-36)」 줄의 걸림이 0 이 아니고 판당 눌린 초
#        20초 이상. 그리고 **걸린 층 평균이 21 이상**(21 미만이면 문이 앞으로 샌 것이다).
#     ② **뒤에 «사건»이 더 서는가(이것이 D 의 물음이다)** — 새 자(절대 자) 뒤(층 21+)
#        판당이 A 팔 **3.00 → 4.5 이상**(1.5배). D-35 는 여기서 1.67 로 «줄었다».
#     ③ **회복이 «시간»을 갖는가** — 뒤 칸 회복초중앙이 A 팔 18.2 보다 **길 것.**
#        같거나 짧으면 눌러도 곧바로 되차는 것이라 D-29~33 과 같은 패배다.
#     ④ **앞을 한 톨도 안 건드렸는가** — 앞(층 1-20) 판당 무너짐이 A 팔 23.33 의
#        **1.1배 이내**, 죽음 합이 12 의 **1.1배 이내.** ★ 이 갈래는 앞에 방아쇠가
#        아예 없으므로 D-35 의 1.5/1.3 배보다 **빡빡하게** 잡는다 — 그런데도 앞이
#        움직였다면 그것은 「샜다」는 뜻이고, 그 자체가 봐야 할 결함이다.
#     ⑤ **판이 더 얕아지지 않았는가** — 최고층이 A 팔 29.67 의 **85% 이상**(25.2).
#   ★ ②③ 이 서고 ④⑤ 가 살아 있을 때만 기본값을 켠다. 하나라도 어긋나면 ☒ 로 닫고
#     무엇이 어떻게 졌는지를 ROADMAP 에 적는다 — **진 것도 답이다**(D-29~35 가 그랬다).
set -u
cd /Users/lbs/source/personal/necro
MIN=${MIN:-9}; SEEDS=${SEEDS:-1,3,7}
node tools/chrome_guard.mjs || true

for arm in A D5; do
  OUT="tmp/d36_${arm}.log"
  [ -s "$OUT" ] && { echo "== $OUT 이미 있음 · 건너뜀 =="; continue; }
  echo "═════ $arm → $OUT · $(date +%H:%M:%S) ═════"
  if [ "$arm" = "A" ]; then K=""; else K="__DEEPCAP=0.5"; fi
  NECRO_KNOBS="$K" node tools/start_probe.mjs "$MIN" "$SEEDS" > "$OUT" 2>&1
  echo "== $arm 끝 · $(date +%H:%M:%S) ==" >&2
done

for arm in A D5; do
  echo ""; echo "═════ $arm (tmp/d36_${arm}.log) ═════"
  grep -A 8 '절대 자' "tmp/d36_${arm}.log"
  grep    '깊이눌림(D-36)' "tmp/d36_${arm}.log"
  grep -A 3 '최고층' "tmp/d36_${arm}.log" | head -8
  grep    '죽음' "tmp/d36_${arm}.log" | head -3
done
