#!/bin/bash
# ★ 긴 측정은 저절로 떨어져 나간다(600초 상한에 잘리지 않게) — tools/ab_guard.sh
. "$(dirname "$0")/ab_guard.sh"
# ══ D-30 · **세 번째 갈래 — 관문이 «되세우는 손»을 잠근다** (battle.js __RAISECHOKE) ══
#
#   D-29 가 닫으면서 수와 함께 남긴 답이 이 문을 냈다: **뒤의 병목은 마나가 아니라 «쿨»이다.**
#   D-27 A 팔(지금 켜져 있는 것)의 뒤 세 칸은 막힘쿨% **75 · 68 · 52** 인데
#   막힘마나% 는 **0 · 0 · 0** 이다. MANA_WALL(초당 되살리기 0.75몫)이 마나를 늘 채워 놔서
#   태워도 다음 소환 전에 다시 찬다 — 그래서 D-29 의 태움은 뒤를 안 물고 **앞으로 샜다**
#   (앞 막힘마나 22·29 → 35·35 · 앞 6분 죽음 4.33 → 6.00).
#
#   ☞ **그러니 이미 무는 축을 문다** — 무너진 직후 **되세우기가 한동안 안 되게** 한다.
#     관문 수법(pool·curse·charge·add)이 터질 때 소환 셋(raise·ghoul·golem)의 재사용을
#     제 쿨의 `__RAISECHOKE` 배로 밀어 올린다(이미 그보다 길면 그대로 둔다).
#   ★ **잃음 총량은 한 톨도 안 늘린다** — 소환수는 하나도 안 깎는다(D-26 ④ 가 막는 자리).
#   ★ **절규(howl)에는 안 붙인다** — 거기 얹으면 갈래가 또 하나가 아니라 같은 하나다.
#   ★ 기본값은 재기 전까지 **한 톨도 안 바꾼다**(__RAISECHOKE = 0 · 문만 나 있다).
#
#   판정 (재기 전에 적는다 · 견줄 팔은 이미 디스크에 있다: tmp/d27_rare.log · 같은 씨앗 열둘)
#     ① **손잡이가 도는가** — 9분 자의 「그 한 방에 손빼앗음」이 **25% 위로.**
#        0 이면 이미 쿨이던 것을 더 민 것뿐이다([[knob-that-does-nothing]]).
#     ② **그 축이 실제로 더 무는가** — 뒤(21~40 · 41~60 · 61+)의 **막힘쿨%** 가 A 팔
#        (75 · 68 · 52)보다 **셋 다 오르고**, 여지가 제일 큰 **61+ 칸이 60% 위로.**
#     ③ **사건이 «커져야» 한다 — 수가 아니라 «무너져 있는 시간»이다.**
#        ★ 여기서 자를 D-27 의 실패에서 고쳐 쓴다([[threshold-and-ruler-must-match]]) —
#          되세우기를 늦추면 사건 «수»는 되레 줄 수 있다(한 번이 길어지므로).
#        · 뒤 **회복초중앙**이 A 팔(10.4 / 13.3 / 9.1)보다 **셋 다 오른다.**
#        · 그러면서 뒤(층 21+) 무너짐 판당이 **17.5 아래로 안 내려간다**(A 팔 21.83 의 80%).
#          그 아래면 사건이 «상태»로 굳은 것이다(D-27 B 팔이 그렇게 졌다).
#     ④ **끝이 되면 안 된다** — 회복초중앙이 A 팔의 **두 배 아래**(20.8 / 26.6 / 18.2)이고
#        「안 돌아옴」이 뒤 무너짐의 **5% 아래**(A 팔 2/262 = 0.8%).
#        그리고 군세/상한이 뒤 세 칸 다 **0.45 위**(A 팔 0.57 / 0.60 / 0.64 · B 팔은 0.35~0.45 로
#        눌러앉아 졌다).
#     ⑤ **앞 6분이 안 물러야 한다** — 앞 6분 죽음이 A 팔(4.33)의 ±20% 안(3.46~5.20).
#        ★ D-29 가 정확히 여기서 졌다 — 뒤를 노린 손잡이가 앞으로 샜다.
#     ⑥ **쉬워지지도 어려워지지도 않는다** — 20분 최고층이 A 팔(61.58)의 −10%(55.4) 위이고
#        D-24 기준(66.5)의 115%(76.5) 아래.
#   ①~⑥ 을 다 세운 팔이 있으면 그 값을 기본값으로 옮긴다. 없으면 **안 켠다** — 그리고
#   「쿨을 잠가도 뒤에 갈래가 안 선다」를 수와 함께 적고 다음 갈래를 찾는다.
#
#   ★ 사다리부터 (9분 × 씨앗 셋) — 잠금이 값을 따라 오르는지, 그리고 「손빼앗음」이 같이
#     오는지를 먼저 본다. 관문은 5층마다 서므로 9분이면 넉넉히 여러 번 터진다
#     ([[floor-far-from-threshold]] — 바닥이 0 인 자로는 못 잰다).
set -u
REPO=/Users/lbs/source/personal/necro
cd "$REPO" || exit 1
MIN=${MIN:-20}
SEEDS=${SEEDS:-"1,3,7,9,11,13,2,4,6,8,10,12"}   # d27_rare / d24_base 와 **같은 판**

node tools/chrome_guard.mjs 2>&1 | tail -2

# ── 0) 잠금이 값을 따라 오르는가 (9분 × 씨앗 셋) ───────────────────────────
echo "═════ 0) 사다리 · 9분 × 씨앗 13,1,3 · $(date +%H:%M) ═════"
for c in 0 2 3 5; do
  OUT="tmp/d30_lad_${c}.log"
  [ -s "$OUT" ] && { echo "== $OUT 이미 있음 · 건너뜀 =="; continue; }
  NECRO_KNOBS="__RAISECHOKE=$c" node tools/start_probe.mjs 9 "13,1,3" > "$OUT" 2>&1
  echo "── RAISECHOKE=$c ──"
  grep '소환잠금(D-30)' "$OUT" || echo "  (소환잠금 줄 없음 — 손잡이가 0 이거나 관문이 안 터졌다)"
  grep -A 6 '뒤에서 왜 자리를 못 채우나' "$OUT"
done

# ── 0b) **판이 한 톨도 안 바뀌었는지** — 손잡이 0 은 옛 판과 «바이트까지» 같아야 한다.
#   d29_lad_0.log 는 같은 자(9분 × 씨앗 13,1,3)를 **이 수정 전에** 기본값으로 찍은 것이다.
echo "── 0b) 문만 낸 것이 맞는가 (d30_lad_0 ↔ d29_lad_0) ──"
if [ -s tmp/d29_lad_0.log ] && [ -s tmp/d30_lad_0.log ]; then
  if diff -q <(grep -v '소환잠금' tmp/d30_lad_0.log) tmp/d29_lad_0.log >/dev/null; then
    echo "  ✔ 바이트까지 같다 — 기본값에서 판이 한 톨도 안 바뀌었다"
  else
    echo "  ✘ 갈렸다 — 아래 차이를 먼저 볼 것"; diff <(grep -v '소환잠금' tmp/d30_lad_0.log) tmp/d29_lad_0.log | head -20
  fi
else echo "  (견줄 로그가 없다)"; fi

# ── 1) 두 팔 (20분 × 씨앗 열둘) ────────────────────────────────────────────
for c in 3 5; do
  OUT="tmp/d30_c${c}.log"
  [ -s "$OUT" ] && { echo "== $OUT 이미 있음 · 건너뜀 =="; continue; }
  echo "═════ RAISECHOKE=$c → $OUT · $(date +%H:%M) ═════"
  NECRO_KNOBS="__RAISECHOKE=$c" node tools/start_probe.mjs "$MIN" "$SEEDS" > "$OUT" 2>&1
  echo "== $c 끝 · $(date +%H:%M:%S) ==" >&2
done

# ── 2) 견줌 ────────────────────────────────────────────────────────────────
sum () {   # $1 = 로그
  local f="$1"
  grep -A 8 '군대가 무너지는 사건' "$f"
  grep -A 6 '뒤에서 왜 자리를 못 채우나' "$f"
  grep '소환잠금(D-30)' "$f"
  awk '$1=="360"  {print "  앞 6분 죽음(평균) : " $NF}' "$f"
  awk '$1=="1200" {print "  20분 최고층(평균) : " $2}'  "$f"
}
echo ""
echo "═════ 견줄 팔(D-27 A 「드묾」 · 지금 켜져 있는 것) : tmp/d27_rare.log ═════"
sum tmp/d27_rare.log
for c in 3 5; do
  echo ""; echo "═════ RAISECHOKE=$c (tmp/d30_c${c}.log) ═════"
  sum "tmp/d30_c${c}.log"
  grep -A 10 '무엇이 소환수를 죽였나' "tmp/d30_c${c}.log"
done
