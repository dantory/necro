#!/usr/bin/env bash
# ── D-22b ㉠ · 손잡이를 더 돌린다 (0 · 0.03 · 0.05 · 0.10) ────────────────
#
# ㉡ 이 통과했다(씨앗 쉰넷 · −0.04층 ±1.09). 닷새를 막고 있던 「최고층이
# 깎인다」는 벽이 **잡음이었다.** 그러니 이제 막힌 것은 ㉠ 하나다 —
# 저주·장판의 한 대당 이빨이 10% 이상. 0.03 에서 저주 8.3 · 장판 4.9 로
# 아직 못 닿았고, 그 위를 못 보고 있었다.
#
# 여기서 네 팔을 **같은 씨앗 스물넷** 위에 세워 ㉠·㉡·㉢ 을 한 번에 읽는다.
#   ㉠ 이빨%  = 표의 curse · 「한 장판당」 줄(D-22c 자 · 틱 칸은 안 본다)
#   ㉡ 최고층 = 1200초 줄의 층 (문턱 −5%)
#   ㉢ 앞6분  = 360초 줄의 죽음 (안 늘 것)
# ★ 돌진은 이미 0.03 에서도 무리에 따라 넘친다(무리 I 1182%) — 넘침은
#   「세다」가 아니라 **자가 못 읽는다**는 뜻이니 판정에서 뺀다.
. "$(dirname "$0")/ab_guard.sh"
set -u
cd "$(dirname "$0")/.."
node tools/chrome_guard.mjs >/dev/null 2>&1 || true

SEEDS=1,3,7,9,11,13,2,4,6,8,10,12,5,15,17,19,21,23,14,16,18,20,22,24

for k in 0 0.03 0.05 0.10; do
  out="tmp/d22g_${k}.log"
  echo "── __GATE_MIN=$k · 씨앗 24 · 20분 ──"
  NECRO_KNOBS="__GATE_MIN=$k" node tools/start_probe.mjs 20 "$SEEDS" > "$out" 2>&1
  echo "  끝 · $(wc -l < "$out") 줄"
done

echo
echo "════ 손잡이별 · 씨앗 24 · 20분 ════"
printf "%8s %10s %10s %10s %10s %10s\n" 손잡이 저주이빨% 장판이빨% 돌진이빨% 20분최고층 앞6분죽음
for k in 0 0.03 0.05 0.10; do
  f=tmp/d22g_${k}.log
  cu=$(awk '$1=="curse"{print $4}'  "$f" | tail -1)
  ch=$(awk '$1=="charge"{print $4}' "$f" | tail -1)
  po=$(grep -o '한 장판당 이빨 [0-9.]*%' "$f" | tail -1 | grep -o '[0-9.]*')
  fl=$(awk '$1=="1200"{print $2}'   "$f" | tail -1)
  de=$(awk '$1=="360" {print $NF}'  "$f" | tail -1)
  printf "%8s %10s %10s %10s %10s %10s\n" "$k" "${cu:--}" "${po:--}" "${ch:--}" "${fl:--}" "${de:--}"
done
