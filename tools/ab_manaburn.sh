#!/bin/bash
# ★ 긴 측정은 저절로 떨어져 나간다(600초 상한에 잘리지 않게) — tools/ab_guard.sh
. "$(dirname "$0")/ab_guard.sh"
# ══ D-29 · **두 번째 «무너짐» 갈래 — 관문이 «마나를» 태운다** (battle.js __MANABURN) ══
#
#   D-28 이 닫으면서 남긴 일감 그대로다: 뒤(층 21+)의 무너짐 21.83 은 **절규 하나에 통째로
#   걸려 있다**(잃음 막타 71% · 깎은몫 96% · 61층+ 는 97%). 한 갈래에 다 걸린 것 자체가
#   문제이고, 절규 안에서 값을 깎는 길은 D-28 이 이미 막다른 곳임을 보였다
#   (넘침 75% 는 낭비가 아니라 «일격의 값»이었다 — 지우면 사건도 같이 사라진다).
#
#   ☞ **그래서 다른 축을 짚는다 — 소환수를 «또» 지우는 것이 아니라 «되세우는 힘»이다.**
#     D 가 죽음의 사진에서 이미 읽어 둔 뿌리가 그것이다: 일곱 죽음이 전부 **군세 0~3 ·
#     마나 0~6** 이었고, 죽인 것은 「무너진 뒤 **마나가 없어 다시 못 세우는 것**」이었다.
#     그런데 뒤에서는 MANA_WALL(회복의 바닥 = 초당 되살리기 0.75몫)이 그 자리를 메워
#     **무너져도 즉시 복구된다** — 그래서 무너짐이 «사건»이 아니라 «상태»다.
#     실제로 d27_rare 의 「왜 자리를 못 채우나」 표에서 뒤 세 칸의 **막힘마나% 가 전부 0** 이다
#     (앞은 22~29%). 뒤에 마나가 무는 자리를 만드는 것이 이 A/B 다.
#   ★ **잃음 총량은 한 톨도 안 늘린다** — 태우는 것은 마나뿐이다(D-26 ④ 가 막는 자리).
#   ★ **절규에는 안 붙인다** — 거기 얹으면 갈래가 또 하나가 아니라 같은 하나다.
#   ★ 기본값은 재기 전까지 **한 톨도 안 바꾼다**(__MANABURN = 0 · 문만 나 있다).
#
#   판정 (재기 전에 적는다 · 견줄 팔은 이미 디스크에 있다: tmp/d27_rare.log · 같은 씨앗 열둘)
#     ① **손잡이가 도는가** — 9분 자의 「그 한 방에 마름(<6)」이 **25% 위로.**
#        0 이면 태우기는 하되 손을 못 묶은 것이다(허공을 태운다 · [[knob-that-does-nothing]]).
#     ② **두 번째 갈래가 실제로 무는가** — 뒤(층 21~40 · 41~60 · 61+)의 **막힘마나%** 가
#        지금 **0 · 0 · 0** 인데, 세 칸 중 **둘 이상이 5% 위로.**
#        (이 칸이 그대로 0 이면 마나를 태워도 소환이 안 막힌 것 = 갈래가 안 선 것이다.)
#     ③ **사건이 늘어야 한다** — 뒤(층 21+) 무너짐 판당이 **23.0 위로**(A 팔 21.83 의 +5%).
#        ★ 21.83 아래로 내려가면 얻은 것이 없으니 그 자리에서 탈락.
#     ④ **끝이 되면 안 된다** — 뒤 회복초중앙이 A 팔(10.4 / 13.3 / 9.1)의 **두 배 아래**
#        (20.8 / 26.6 / 18.2). 「돌아오지 않는 무너짐」은 사건이 아니라 죽음이다.
#     ⑤ **앞 6분이 안 물러야 한다** — 앞 6분 죽음이 A 팔(4.33)의 ±20% 안(3.46~5.20).
#     ⑥ **쉬워지지도 어려워지지도 않는다** — 20분 최고층이 A 팔(61.58)의 −10%(55.4) 위이고
#        D-24 기준(66.5)의 115%(76.5) 아래.
#   ①~⑥ 을 다 세운 팔이 있으면 그 값을 기본값으로 옮긴다. 없으면 **안 켠다** — 그리고
#   「마나를 태워도 뒤에 갈래가 안 선다」를 수와 함께 적고 다음 갈래를 찾는다.
#
#   ★ 사다리부터 (9분 × 씨앗 셋) — 태움이 값을 따라 오르는지, 그리고 「마름」이 같이 오는지를
#     먼저 본다. 관문은 5층마다 서므로 9분이면 넉넉히 여러 번 터진다([[floor-far-from-threshold]]).
set -u
REPO=/Users/lbs/source/personal/necro
cd "$REPO" || exit 1
MIN=${MIN:-20}
SEEDS=${SEEDS:-"1,3,7,9,11,13,2,4,6,8,10,12"}   # d27_rare / d24_base 와 **같은 판**

node tools/chrome_guard.mjs 2>&1 | tail -2

# ── 0) 태움이 값을 따라 오르는가 (9분 × 씨앗 셋) ───────────────────────────
echo "═════ 0) 사다리 · 9분 × 씨앗 13,1,3 · $(date +%H:%M) ═════"
for b in 0 0.20 0.35 0.55; do
  OUT="tmp/d29_lad_${b}.log"
  [ -s "$OUT" ] && { echo "== $OUT 이미 있음 · 건너뜀 =="; continue; }
  NECRO_KNOBS="__MANABURN=$b" node tools/start_probe.mjs 9 "13,1,3" > "$OUT" 2>&1
  echo "── MANABURN=$b ──"
  grep '마나태움(D-29)' "$OUT" || echo "  (마나태움 줄 없음 — 손잡이가 0 이거나 관문이 안 터졌다)"
  grep -A 6 '뒤에서 왜 자리를 못 채우나' "$OUT"
done

# ── 0b) **판이 한 톨도 안 바뀌었는지** — 손잡이 0 은 옛 판과 «바이트까지» 같아야 한다.
#   d28_lad_0.60.log 는 같은 자(9분 × 씨앗 13,1,3)를 **이 수정 전에** 기본값으로 찍은 것이다.
echo "── 0b) 문만 낸 것이 맞는가 (d29_lad_0 ↔ d28_lad_0.60) ──"
if [ -s tmp/d28_lad_0.60.log ] && [ -s tmp/d29_lad_0.log ]; then
  if diff -q <(grep -v '마나태움' tmp/d29_lad_0.log) tmp/d28_lad_0.60.log >/dev/null; then
    echo "  ✔ 바이트까지 같다 — 기본값에서 판이 한 톨도 안 바뀌었다"
  else
    echo "  ✘ 갈렸다 — 아래 차이를 먼저 볼 것"; diff <(grep -v '마나태움' tmp/d29_lad_0.log) tmp/d28_lad_0.60.log | head -20
  fi
else echo "  (견줄 로그가 없다)"; fi

# ── 1) 두 팔 (20분 × 씨앗 열둘) ────────────────────────────────────────────
for b in 0.35 0.55; do
  OUT="tmp/d29_b${b}.log"
  [ -s "$OUT" ] && { echo "== $OUT 이미 있음 · 건너뜀 =="; continue; }
  echo "═════ MANABURN=$b → $OUT · $(date +%H:%M) ═════"
  NECRO_KNOBS="__MANABURN=$b" node tools/start_probe.mjs "$MIN" "$SEEDS" > "$OUT" 2>&1
  echo "== $b 끝 · $(date +%H:%M:%S) ==" >&2
done

# ── 2) 견줌 ────────────────────────────────────────────────────────────────
sum () {   # $1 = 로그
  local f="$1"
  grep -A 8 '군대가 무너지는 사건' "$f"
  grep -A 6 '뒤에서 왜 자리를 못 채우나' "$f"
  grep '마나태움(D-29)' "$f"
  awk '$1=="360"  {print "  앞 6분 죽음(평균) : " $NF}' "$f"
  awk '$1=="1200" {print "  20분 최고층(평균) : " $2}'  "$f"
}
echo ""
echo "═════ 견줄 팔(D-27 A 「드묾」 · 지금 켜져 있는 것) : tmp/d27_rare.log ═════"
sum tmp/d27_rare.log
for b in 0.35 0.55; do
  echo ""; echo "═════ MANABURN=$b (tmp/d29_b${b}.log) ═════"
  sum "tmp/d29_b${b}.log"
  grep -A 10 '무엇이 소환수를 죽였나' "tmp/d29_b${b}.log"
done
