#!/bin/bash
# ★ 긴 측정은 저절로 떨어져 나간다(하트비트 600초 상한에 잘리지 않게) — tools/ab_guard.sh
. "$(dirname "$0")/ab_guard.sh"
# ══ A-1 다음 축 — **깊은 층의 장판은 어디로 갔나** ═══════════════════════════
#
#   A-1 의 답(2026-08-14 07:41)은 「50층 아래로는 네크로에게 한 대도 안 닿는다」였고,
#   닿았던 피해의 정체는 얕은 띠 90% · 25-49층 100% 가 **pool**(장판)이었다.
#   장판만이 소환수 벽을 지나쳐 네크로가 선 자리(중앙 r=92)를 때린다. 그런데 장판을
#   까는 것은 **관문 주인 하나**(역병술사)뿐이고 관문은 5층마다 온다 — 50-99층에도
#   관문이 열 번 있는데 장판이 0 이다. 셋 중 어느 것인지를 여기서 가른다:
#     ① 그 띠에 관문이 안 섰다        → 「관문 0번」으로 찍힌다
#     ② 주인이 수법을 쓰기 전에 죽는다 → 「한 번에 산 시간 < 3.3초」·「못 쓰고 죽은 관문」
#     ③ 쓰는데 안 닿는다              → 수법은 도는데 장판 수만 0
#   (첫 장판까지 3.3초 = born 0.8 + mechCd(cd×0.6) 1.7 + tell 0.8)
#
#   ★ 손은 하나도 안 댄다 — 읽기만 하는 자라 base 그대로다(A/B 가 그대로 성립한다).
#   ★ 한 판은 표본 하나다(seed-the-probe) — 씨앗 1·3·9 셋을 다 돌리고 같이 읽는다.
#   ★ 3분 연습에서 이미 나온 것: 얕은 관문의 주인은 한 번에 21.6초를 살고 관문당
#     수법 5.5번 · 장판 10장을 깐다. 깊은 관문이 이 숫자의 어디쯤인지가 답이다.
set -u
REPO=/Users/lbs/source/personal/necro
cd "$REPO" || exit 1
MIN=30
# 썩은 렌더러 하나가 한 시간 반을 통째로 못 믿게 만든다(TOOLS.md).
node tools/chrome_guard.mjs || echo "(chrome_guard 실패 — 그대로 간다)"

for s in 1 3 9; do
  echo "───────── SEED $s · $(date +%H:%M) ─────────"
  LH_SEED=$s node tools/loop_health.mjs "$MIN" "tmp/a1g_$s.json" 2>&1 | tail -20 || echo "FAIL $s"
done
echo "═════ 끝 · $(date +%H:%M) ═════"

# ── 셋을 같이 읽는다 ──────────────────────────────────────────────────────
python3 - <<'PY'
import json, pathlib
띠들 = ["1-9", "10-24", "25-49", "50-99", "100+"]
칸 = ("관문", "보스초", "수법", "장판", "못쓰고죽음")
합 = {k: {c: 0.0 for c in 칸} for k in 띠들}
층 = {k: [] for k in 띠들}
print()
for s in (1, 3, 9):
    try: d = json.loads(pathlib.Path(f"tmp/a1g_{s}.json").read_text())
    except Exception: print(f"씨앗 {s}: 자료 없음"); continue
    G = ((d.get("시간") or {}).get("위험") or {}).get("관문") or {}
    if not G: print(f"씨앗 {s}: 관문 자료 없음"); continue
    말 = " · ".join(f"{k} {G[k]['관문']}번/{G[k]['장판']}장" for k in 띠들 if G.get(k, {}).get("관문"))
    print(f"씨앗 {s} — 최고층 {d['rows'][-1]['최고층']} · {말}")
    for k, g in G.items():
        if k not in 합: continue
        for c in 칸: 합[k][c] += g.get(c, 0)
        층[k] += g.get("층") or []

print("\n── 씨앗 셋을 합친 관문 ──")
for k in 띠들:
    g = 합[k]
    if not g["관문"]: continue
    print(f"  {k:>6}층 · 관문 {g['관문']:.0f}번 · 주인이 산 시간 {g['보스초']:.0f}초 "
          f"(한 번에 **{g['보스초']/g['관문']:.1f}초**) · 수법 {g['수법']:.0f}번 "
          f"(관문당 {g['수법']/g['관문']:.1f}) · 장판 {g['장판']:.0f}장 "
          f"· 못 쓰고 죽은 관문 {g['못쓰고죽음']:.0f}/{g['관문']:.0f}번")
    if k in ("50-99", "100+") and 층[k]:
        print(f"         선 층: {' '.join(str(int(f)) for f in sorted(set(층[k])))}")

print("\n판정 — 50-99층 띠를 본다:")
깊, 얕 = 합["50-99"], 합["1-9"]
if not 깊["관문"]:
    print("  ① **관문이 한 번도 안 섰다.** 장판 이전에 관문 자체가 없다 —")
    print("     isGate(f%5==0) 인데 안 섰다면 층을 건너뛰거나 주인이 안 실리는 자리가 있다.")
else:
    산 = 깊["보스초"] / 깊["관문"]
    수 = 깊["수법"] / 깊["관문"]
    print(f"  관문 {깊['관문']:.0f}번 · 한 번에 {산:.1f}초 · 관문당 수법 {수:.1f}번 · 장판 {깊['장판']:.0f}장")
    if 얕["관문"]:
        print(f"  (얕은 관문은 한 번에 {얕['보스초']/얕['관문']:.1f}초 · 관문당 수법 {얕['수법']/얕['관문']:.1f}번 "
              f"· 장판 {얕['장판']:.0f}장)")
    if 산 < 3.3:
        print("  ② **주인이 수법을 쓰기 전에 죽는다**(첫 수법까지 3.3초 필요).")
        print("     → A-1 은 「위험을 키우는」 문제가 아니라 **위험이 화면에 나오기도 전에**")
        print("       치워지는 문제다. 고칠 자리는 값이 아니라 구조 — 주인이 수법을 한 번은")
        print("       쓰고 죽게 하는 것(무적 예고 · 첫 수법을 등장과 함께 · 체력 문턱마다 발동).")
    elif 깊["장판"] == 0:
        print("  ③ **수법은 도는데 장판이 0 이다** — 이 띠의 주인이 역병술사가 아닐 수 있다")
        print("     (gatelordFor 는 floor/5-1 로 넷을 돌려 쓴다 — 깊은 층의 주인 분포를 볼 것).")
    else:
        print("  ④ 장판은 깔리는데 피해가 0 이었다 — 닿는 자리(반경·네크로 위치) 쪽을 볼 것.")
PY
git -C "$REPO" status --porcelain js/
