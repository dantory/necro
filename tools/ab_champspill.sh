#!/bin/bash
# ★ 긴 측정은 저절로 떨어져 나간다(600초 상한에 잘리지 않게) — tools/ab_guard.sh
. "$(dirname "$0")/ab_guard.sh"
# ══ D-28 · **같은 「모음」을 덜 흘리게 — 절규 넘침 75%** (battle.js __CHAMP_HOWL) ══
#
#   D-27 이 팔 A 「드묾」을 켜서 뒤 무너짐을 14.67 → 21.83 으로 올렸다. 그런데 같은 자가
#   **넘침 75.2%** 를 같이 찍었다(tmp/d27_pre_rare.log · 9분 자):
#       기준(0.25) : 터짐 78 · 맞은대수 239 · 한대당 이빨 41.8% · **넘침 1.3%**
#       지금(0.60) : 터짐 39 · 맞은대수 137 · 한대당 이빨 95.2% · **넘침 75.2%**
#   곧 절규가 쏟는 것의 **4분의 3이 허공**이다. 한 대가 밑 체력의 1.43배인데, 맞는 소환수는
#   이미 이빨에 깎여 **최대체력의 4분의 1쯤**만 남아 있기 때문이다(95.2% × 24.8% ≈ 23.6%).
#   그리고 그 값을 치렀다 — **20분 최고층이 66.5 → 61.58 로 7.4% 얕아졌다**(D-26 ④ 안이지만
#   공짜가 아니었다).
#
#   ☞ **묻는 것 하나** — 흘리는 것을 줄이면 «사건»이 남는가, 같이 사라지는가.
#     남으면 7.4% 를 되찾는다. 같이 사라지면 넘침 75% 는 **사건의 값**이지 낭비가 아니다.
#     (D-27 이 이미 보인 것: 총량을 줄이면 그냥 쉬워질 뿐이다 — 그래서 ②③ 로 막는다.)
#   ★ 손잡이는 **이미 있다**(`__CHAMP_HOWL`). 새 문을 안 낸다 — 값만 사다리로 훑는다.
#   ★ 기본값은 재기 전까지 **한 톨도 안 바꾼다**(P 0.06 · CD 6.0 · HOWL 0.60).
#
#   판정 (재기 전에 적는다 · 견줄 팔은 이미 디스크에 있다: tmp/d27_rare.log · 같은 씨앗 열둘)
#     ① **덜 흘리는가** — 9분 자의 절규 넘침이 **40% 아래로** (지금 75.2).
#     ② **사건이 남는가** — 뒤(층 21+) 무너짐 판당이 **18.6 위로** (D-27 A 팔 21.83 의 −15%).
#        ★ 14.67(D-27 이전)까지 내려가면 D-27 을 되돌린 것이니 그 자리에서 탈락.
#     ③ **끝이 되면 안 된다** — 뒤 회복초중앙이 A 팔(10.4 / 13.3 / 9.1)의 **두 배 아래.**
#     ④ **앞 6분이 안 물러야 한다** — 앞(층 1~20) 죽음이 A 팔(4.33)의 ±20% 안.
#     ⑤ **되찾되 쉬워지면 안 된다** — 20분 최고층 중앙이 A 팔(61.58) **아래로 안 내려가고**,
#        D-24 기준(66.5)의 **115%(76.5) 위로도 안 간다**.
#   ①②③④⑤ 를 다 세운 팔이 있으면 그 값을 기본값으로 옮긴다. 없으면 **안 켠다** —
#   그때 「넘침 75%」는 낭비가 아니라 사건의 값이라고 적고 이 줄을 닫는다.
#
#   ★ 사다리부터 (9분 × 씨앗 셋) — 넘침이 실제로 값을 따라 내려오는지, 그리고 「맞은대수」가
#     같이 죽는지를 먼저 본다([[knob-that-does-nothing]] · [[play-it-before-measuring-it]]).
#     3분 자로는 못 본다 — 우두머리는 층 10 부터 서고 씨앗이 거기 닿는 데 8분이 든다.
set -u
REPO=/Users/lbs/source/personal/necro
cd "$REPO" || exit 1
MIN=${MIN:-20}
SEEDS=${SEEDS:-"1,3,7,9,11,13,2,4,6,8,10,12"}   # d27_rare / d24_base 와 **같은 판**

node tools/chrome_guard.mjs 2>&1 | tail -2

# ── 0) 넘침이 값을 따라 내려오는가 (9분 × 씨앗 셋) ─────────────────────────
echo "═════ 0) 사다리 · 9분 × 씨앗 13,1,3 · $(date +%H:%M) ═════"
for h in 0.60 0.45 0.35 0.25; do
  OUT="tmp/d28_lad_${h}.log"
  [ -s "$OUT" ] && { echo "== $OUT 이미 있음 · 건너뜀 =="; continue; }
  NECRO_KNOBS="__CHAMP_P=0.06;__CHAMP_HOWL=$h" node tools/start_probe.mjs 9 "13,1,3" > "$OUT" 2>&1
  echo "── HOWL=$h ──"; grep -A 3 '수법이 터지긴 하는가' "$OUT"
done

# ── 1) 두 팔 (20분 × 씨앗 열둘) ────────────────────────────────────────────
for h in 0.45 0.35; do
  OUT="tmp/d28_h${h}.log"
  [ -s "$OUT" ] && { echo "== $OUT 이미 있음 · 건너뜀 =="; continue; }
  echo "═════ HOWL=$h → $OUT · $(date +%H:%M) ═════"
  NECRO_KNOBS="__CHAMP_P=0.06;__CHAMP_HOWL=$h" node tools/start_probe.mjs "$MIN" "$SEEDS" > "$OUT" 2>&1
  echo "== $h 끝 · $(date +%H:%M:%S) ==" >&2
done

echo ""
echo "═════ 견줄 팔(D-27 A 「드묾」) : tmp/d27_rare.log ═════"
grep -A 8 '군대가 무너지는 사건' tmp/d27_rare.log
grep -A 6 '수법이 터지긴 하는가' tmp/d27_rare.log
for h in 0.45 0.35; do
  echo ""; echo "═════ HOWL=$h (tmp/d28_h${h}.log) ═════"
  grep -A 8 '군대가 무너지는 사건' "tmp/d28_h${h}.log"
  grep -A 6 '수법이 터지긴 하는가' "tmp/d28_h${h}.log"
  grep -A 10 '무엇이 소환수를 죽였나' "tmp/d28_h${h}.log"
done
