## 고칠 때 — 원인을 «수로» 먼저 가른다

로드맵에 적힌 원인은 **짐작이다.** 둘 중 어느 쪽인지 재서 갈라라:
· (가) **생기는 자리가 격자다** — 팩 생성 좌표가 격자 오프셋. → **깨어나기 전(잠든) 적 좌표**로
  같은 CV 를 재 본다. 잠든 것부터 CV 가 낮으면 (가)다.
· (나) **쫓는 중에 간격이 보존된다** — 전원이 **같은 속도·같은 목표**라 상대 위치가 그대로 굳는다.
  → 잠든 좌표는 CV 가 높은데 깨어난 뒤 낮아지면 (나)다.
둘 다일 수도 있다. **어느 쪽인지 로그에 수로 적고** 그 자리만 고쳐라.

고칠 때 지켜라:
- **밀도를 깨지 마라.** V-192 의 적 p50 ≥ 12 는 이 판의 회귀선이다.
- (가)면 생성 좌표에 **무리 안에서의 흩뿌림**을 넣는다(무리 중심 주위 반경 안 무작위).
  씨앗 고정 재현성을 깨지 마라 — `Math.random` 말고 판의 시드 RNG 를 써라.
- (나)면 개체마다 **속도에 작은 개인차**와 **목표 지점에 개인 오프셋**을 준다. 속도 평균은
  바꾸지 마라(난이도 밸런스를 건드리는 판이 아니다) — 평균 유지, 분산만 준다.
- 코드 필터(`ctx.filter`)로 칠하거나 `fillRect` 로 그려 때우지 마라. 접지는 불투명 픽셀 아래 경계로.
- 고친 뒤 **같은 자로 다시 재라.** 고치기 전/후 수를 둘 다 적어라.

