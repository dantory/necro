## 통과선 — 재기 전에 못 박는다 (나중에 정하면 자기변호가 된다)

자동조종 실플레이 **120초 · 씨앗 둘(1·2) · 1초마다 표본**. 「화면 안」은 **카메라에 실제로 보이는
사각** 기준(월드 전체 아님). 표본마다 화면 안 살아 있는 적 좌표를 모아 두 수를 낸다:

· **㉠ 최근접 이웃 거리의 변동계수 CV = std/mean ≥ 0.35**
  바닥과 천장이 알려진 자다 — **완전 격자 CV ≈ 0**, **2차원 무작위(포아송) CV ≈ 0.52**.
  0.35 는 그 사이에 있고 격자에서 멀다. (표본당 적 6마리 미만이면 그 표본은 버린다.)
· **㉡ 축 정렬 비율 ≤ 50%**
  각 적에서 최근접 이웃으로 향하는 각도가 **0°·90°·180°·270° 의 ±15° 안**에 드는 비율.
  무작위면 ≈ 33%, 완전 격자면 ≈ 100%. 50% 는 그 사이다.
· 곁들여 볼 것(통과선 아님, 기록만): 화면 안 적 p50(V-192 의 ≥12 를 **깨면 안 된다** — 깨지면 실패),
  frame p95 ≤ 16.7ms, 콘솔 오류 0.

