#!/bin/bash
# ★ 긴 측정은 저절로 떨어져 나간다(600초 상한에 잘리지 않게) — tools/ab_guard.sh
. "$(dirname "$0")/ab_guard.sh"
# ══ D-33 · **회전율 자체를 옮긴다 — 적고 튼튼하게** (core.js __TOUGH) ══
#
#   D-29(마나)·D-30(쿨)·D-31(시체)·D-32(관문폭발) **넷이 다 졌고, 넷 다 같은 모양**이었다:
#   무엇을 태우든 무엇을 물든 **되세움이 그만큼 따라 올랐다**(D-32: 잃음/분 128→148 인데
#   세움/분 134→155). D-32 가 그 까닭을 수로 굳혔다 — 서 있는 군세가 열 마리 안팎인데
#   세움/분이 134~155 이니 **군세 전체가 4초에 한 번 갈린다.** 회복초중앙 10초는 그 회전의
#   두세 바퀴일 뿐이다. **4초짜리 흐름 위에서는 무너짐이 «상태»는 되어도 «사건»이 못 된다.**
#
#   ☞ 그래서 이번엔 태우는 쪽도 무는 쪽도 아니라 **회전율 자체**다:
#     **상한을 내리고 그만큼 한 마리를 두껍고 세게.** 한 마리가 오래 살아야 잃는 것이
#     아깝고, 그제야 무너짐이 사건이 된다.
#   ★ **총량은 일부러 보존한다** — 되받는 몫이 «명목»이 아니라 **실제로 깎인 정수 상한의 비**라
#     (`toughBackMul`), 총체력·총피해가 어느 자리에서나 **정확히 100%** 다
#     (`tools/tough_check.mjs` 표 넷 × t 여섯 = 24칸 전부). 곧 **갈린 것은 «알갱이 크기»뿐**이라
#     뒤에 무슨 일이 나든 그것을 «회전율» 탓이라 말할 수 있다.
#     ✗ 처음엔 명목(1/0.6)^t 로 짰다가 자가 **재기 전에** 잡아냈다 — 초반 상한은 3~8 이라
#       ceil 이 이겨 그 자리 총량이 **139%** 가 됐다(뒤를 노린 손잡이가 앞을 세게 만드는 꼴).
#   ★ 팔은 **t = 1 · 2** 다. t=3 은 초반 상한이 **1** 이 되어 벽이 통째로 없어지고(자 ④),
#     t=0.5 는 초반을 한 톨도 못 움직인다 — 안 움직이는 자리에 팔을 낭비하지 않는다
#     ([[knob-that-does-nothing]]).
#   ★ 기본값은 재기 전까지 **한 톨도 안 바꾼다**(__TOUGH = 0 · 문만 나 있다).
#
#   판정 (재기 전에 적는다 · 견줄 팔은 이미 디스크에 있다: tmp/d27_rare.log · 같은 씨앗 열둘)
#     ① **회전율이 실제로 내려가는가** — 이 팔의 존재 이유다. 뒤 세 칸(21-40/41-60/61-)의
#        **잃음/분이 셋 다 100 아래**로 내려간다(A 팔은 128~148). 안 내려가면 나머지는 볼 것도 없다.
#        · 「세움/분」도 같이 내려가야 한다(상한이 작아졌으니 산수로 그래야 한다).
#          안 내려가면 → 소환이 빈자리를 더 빨리 메우는 것이라 **회전율 축이 아니다.**
#     ② **사건이 «커지는가» — 수가 아니라 «무너져 있는 시간»이다.**
#        뒤 **회복초중앙**이 A 팔(10.4 / 13.3 / 9.1)보다 **셋 다 오른다.** D-32 가 여기서 졌다
#        (무너짐은 +16% 인데 회복초는 되레 줄었다 — 사건이 잘게 쪼개졌다).
#     ③ **그러면서 «상태»로 굳으면 안 된다** — 뒤 무너짐 판당이 **17.5 아래로 안 내려간다**
#        (A 팔 21.83 의 80%). 그 아래면 늘 무너져 있는 것이다(D-27 B 팔이 그렇게 졌다).
#     ④ **끝이 되면 안 된다** — 「안 돌아옴」이 뒤 무너짐의 **5% 아래**(A 팔 0.8%) ·
#        군세/상한이 뒤 세 칸 다 **0.45 위**(A 팔 0.57 / 0.60 / 0.64).
#        ★ 이 팔은 상한 자체가 작아 **군세/상한은 되레 오르기 쉽다** — 그러니 ④는 헐거운 자다.
#          진짜로 볼 것은 ①의 「세움/분」과 아래 ⑥이다([[floor-far-from-threshold]]).
#     ⑤ **앞 6분이 안 물려야 한다** — 앞 6분 죽음이 A 팔(4.33)의 ±20% 안(3.46~5.20).
#        ★ D-29·D-31·D-32 가 전부 여기서 졌다. 그리고 이 팔은 **앞을 물 까닭이 산수로 있다** —
#          초반 상한 4 → t=1 이면 3 · t=2 면 2 다(자 ④). 총량은 보존되지만 **벽의 «머릿수»**는
#          준다(적 여섯을 둘로 막는다). 여기가 이 팔의 제일 큰 위험이다.
#     ⑥ **쉬워지지도 어려워지지도 않는다** — 20분 최고층이 A 팔(61.58)의 −10%(55.4) 위이고
#        D-24 기준(66.5)의 115%(76.5) 아래.
#   ①~⑥ 을 다 세운 팔이 있으면 그 값을 기본값으로 옮긴다. 없으면 **안 켠다** — 그리고
#   「회전율을 내려도 뒤에 사건이 안 선다」를 수와 함께 적는다. 그러면 D 는 손잡이·갈래·회전율
#   세 축을 다 짚은 것이라, 다음은 **판의 얼개**(층·관문 자체)로 넘어간다.
#
REPO="/Users/lbs/source/personal/necro"
cd "$REPO" || exit 1
MIN=${MIN:-20}
SEEDS=${SEEDS:-"1,3,7,9,11,13,2,4,6,8,10,12"}   # d27_rare / d24_base 와 **같은 판**

node tools/chrome_guard.mjs 2>&1 | tail -2

# ── 0) 회전율이 값을 따라 내려가는가 (9분 × 씨앗 셋) ────────────────────────
echo "═════ 0) 사다리 · 9분 × 씨앗 13,1,3 · $(date +%H:%M) ═════"
for t in 0 1 2; do
  OUT="tmp/d33_lad_${t}.log"
  [ -s "$OUT" ] && { echo "== $OUT 이미 있음 · 건너뜀 =="; continue; }
  NECRO_KNOBS="__TOUGH=$t" node tools/start_probe.mjs 9 "13,1,3" > "$OUT" 2>&1
  echo "── TOUGH=$t ──"
  grep -A 7 '뒤에서 왜 자리를 못 채우나' "$OUT"
done

# ── 0b) **판이 한 톨도 안 바뀌었는지** — 손잡이 0 은 옛 판과 «바이트까지» 같아야 한다.
#   d32_lad_0.log 는 같은 자(9분 × 씨앗 13,1,3)를 **이 수정 전에** 찍은 것이다.
#   D-33 은 새로 내는 줄이 없으므로 **통째로** 같아야 한다(관문폭발 줄만 빼고 견준다).
echo "── 0b) 문만 낸 것이 맞는가 (d33_lad_0 ↔ d32_lad_0) ──"
if [ -s tmp/d32_lad_0.log ] && [ -s tmp/d33_lad_0.log ]; then
  if diff -q <(grep -v '관문폭발\|blast' tmp/d33_lad_0.log) <(grep -v '관문폭발\|blast' tmp/d32_lad_0.log) >/dev/null; then
    echo "  ✔ 바이트까지 같다 — 기본값에서 판이 한 톨도 안 바뀌었다"
  else
    echo "  ✘ 갈렸다 — 아래 차이를 먼저 볼 것"
    diff <(grep -v '관문폭발\|blast' tmp/d33_lad_0.log) <(grep -v '관문폭발\|blast' tmp/d32_lad_0.log) | head -20
  fi
else echo "  (견줄 로그가 없다)"; fi

# ── 1) 두 팔 (20분 × 씨앗 열둘) ────────────────────────────────────────────
for t in 1 2; do
  OUT="tmp/d33_t${t}.log"
  [ -s "$OUT" ] && { echo "== $OUT 이미 있음 · 건너뜀 =="; continue; }
  echo "═════ TOUGH=$t → $OUT · $(date +%H:%M) ═════"
  NECRO_KNOBS="__TOUGH=$t" node tools/start_probe.mjs "$MIN" "$SEEDS" > "$OUT" 2>&1
  echo "== $t 끝 · $(date +%H:%M:%S) ==" >&2
done

# ── 2) 견줌 ────────────────────────────────────────────────────────────────
sum () {   # $1 = 로그
  local f="$1"
  grep -A 8 '군대가 무너지는 사건' "$f"
  grep -A 7 '뒤에서 왜 자리를 못 채우나' "$f"
  awk '$1=="360"  {print "  앞 6분 죽음(평균) : " $NF}' "$f"
  awk '$1=="1200" {print "  20분 최고층(평균) : " $2}'  "$f"
}
echo ""
echo "═════ 견줄 팔(D-27 A 「드묾」 · 지금 켜져 있는 것) : tmp/d27_rare.log ═════"
sum tmp/d27_rare.log
grep -A 10 '무엇이 소환수를 죽였나' tmp/d27_rare.log
for t in 1 2; do
  echo ""; echo "═════ TOUGH=$t (tmp/d33_t${t}.log) ═════"
  sum "tmp/d33_t${t}.log"
  grep -A 10 '무엇이 소환수를 죽였나' "tmp/d33_t${t}.log"
done
