#!/bin/bash
# ★ 긴 측정은 저절로 떨어져 나간다(600초 상한에 잘리지 않게) — tools/ab_guard.sh
. "$(dirname "$0")/ab_guard.sh"
# ══ D-27 · **잃음 쪽 손잡이 — 같은 양을 «드물게·크게»** (battle.js __CHAMP_P / __CHAMP_CD) ══
#
#   D-26 이 소환 쪽 문을 끝까지 열고도 순증을 못 늘렸다(세움 102→118 인데 순증 +2 그대로).
#   뒤의 군세 0.6 은 **들고 나는 것이 같은 평형**이므로, 남은 손잡이는 «잃음» 하나다.
#   그 잃음이 무엇인지는 이미 디스크에 있었다 (tmp/d24_base.log 「무엇이 소환수를 죽였나」):
#     · 절규(howl) 막타 **71%** · 깎은몫 **96%** — 나머지 일곱 갈래를 다 합쳐도 4% 다.
#     · 깊이가 붙을수록 더 그렇다: 깎은몫 howl% 가 21-40 **86** · 41-60 **92** · 61+ **97**.
#     · 절규는 6초마다 · 졸개의 16% 가 우두머리 → **줄곧 터진다.** 그래서 무너짐이
#       «사건»이 아니라 **«상태»** 다(D-23 이 이름 붙인 바로 그것).
#   → 그러니 **총량을 줄이지 않는다**(줄이면 그냥 쉬워질 뿐이다 · D-26 ④ 가 막는다).
#     같은 양을 **모아서** 터뜨린다. 사이가 비면 군세가 차고, 터지면 통째로 무너진다.
#       팔 A 「드묾」  P 0.16 → **0.06** · 절규 0.25 → **0.60**  (초당 총량 90%)
#       팔 B 「뜸함」  CD 6초 → **14초** · 절규 0.25 → **0.60**  (초당 총량 103%)
#     0.60 은 소환수 밑 체력(floorHp × RAISE_HP 0.42)의 **1.43배** — 한 번에 지운다.
#   ★ 두 팔은 「드묾을 «자리»로 낼 것인가 «시간»으로 낼 것인가」를 가른다. 총량은 같다.
#   ★ 기본값은 재기 전까지 **한 톨도 안 바꾼다**(0.16 · 6.0 · 0.25).
#
#   판정 (재기 전에 적는다 · 견줄 팔은 이미 디스크에 있다: tmp/d24_base.log · 같은 씨앗 열둘)
#     ① **사이가 차는가** — 뒤(층 21+) 군세/상한이 **0.70 위로**(기준 0.58 · 0.59 · 0.65).
#     ② **사건이 되는가** — 뒤(21+) 무너짐이 **판당 14.67 아래로 안 내려간다.**
#        ★ 되레 늘어야 맞다 — 0.70 에 닿아야 자가 다시 겨눠지기 때문이다(start_probe 90행).
#        회복초중앙이 기준(11.6~16.3초)의 **두 배를 넘으면 «사건»이 아니라 «끝»**이다 → 탈락.
#     ③ **앞 6분이 안 물러야 한다** — 앞(층 1~20) 죽음이 기준 팔의 ±20% 안(기준 4.42/판).
#        (우두머리는 층 10 부터 서므로 앞은 거의 안 움직여야 맞다 — 크게 움직이면 그것이 신호다.)
#     ④ **깊은 층이 도로 안전해지면 안 된다** — 20분 최고층 중앙이 기준(66.5)의 **115% 아래.**
#   ①②를 같이 넘고 ③④가 서면 그 팔의 값을 기본값으로 옮긴다. 아니면 **안 켠다.**
#
#   ★ 재기 전에 **팔이 사는지부터 본다**([[knob-that-does-nothing]]) — 3분 자로는 못 본다.
#     우두머리는 층 10 부터 서고 씨앗 하나가 층 21 에 닿는 데 약 8분이 든다(d24_base).
#     그래서 앞머리에 **9분 × 씨앗 13** 을 두 팔로 돌려 「절규 터짐 수」와 「한 대당 이빨%」가
#     실제로 갈리는지 먼저 찍는다. 안 갈리면 그 자리에서 멈춘다(20분 × 12판을 안 버린다).
set -u
REPO=/Users/lbs/source/personal/necro
cd "$REPO" || exit 1
MIN=${MIN:-20}
SEEDS=${SEEDS:-"1,3,7,9,11,13,2,4,6,8,10,12"}   # d24_base 와 **같은 판**이라야 맞댈 수 있다

node tools/chrome_guard.mjs 2>&1 | tail -2

# ── 0) 팔이 사는가 (9분 × 씨앗 13) ─────────────────────────────────────────
echo "═════ 0) 팔이 도는지부터 · 9분 × 씨앗 13 · $(date +%H:%M) ═════"
for pre in "base:" "rare:__CHAMP_P=0.06;__CHAMP_HOWL=0.60" "slow:__CHAMP_CD=14;__CHAMP_HOWL=0.60"; do
  tag=${pre%%:*}; kn=${pre#*:}
  OUT="tmp/d27_pre_${tag}.log"
  [ -s "$OUT" ] && { echo "== $OUT 이미 있음 · 건너뜀 =="; continue; }
  NECRO_KNOBS="$kn" node tools/start_probe.mjs 9 "13" > "$OUT" 2>&1
  echo "── $tag ──"; grep -A 7 '수법이 터지긴 하는가' "$OUT"
done

# ── 1) 두 팔 (20분 × 씨앗 열둘) ────────────────────────────────────────────
for arm in "rare:__CHAMP_P=0.06;__CHAMP_HOWL=0.60" "slow:__CHAMP_CD=14;__CHAMP_HOWL=0.60"; do
  tag=${arm%%:*}; kn=${arm#*:}
  OUT="tmp/d27_${tag}.log"
  [ -s "$OUT" ] && { echo "== $OUT 이미 있음 · 건너뜀 =="; continue; }
  echo "═════ $tag ($kn) → $OUT · $(date +%H:%M) ═════"
  NECRO_KNOBS="$kn" node tools/start_probe.mjs "$MIN" "$SEEDS" > "$OUT" 2>&1
  echo "== $tag 끝 · $(date +%H:%M:%S) ==" >&2
done

echo ""
echo "═════ 견줄 팔(기준) : tmp/d24_base.log ═════"
grep -A 8 '뒤에서 왜 자리를 못 채우나' tmp/d24_base.log
grep -A 8 '군대가 무너지는 사건' tmp/d24_base.log
for tag in rare slow; do
  echo ""; echo "═════ $tag (tmp/d27_${tag}.log) ═════"
  grep -A 8 '뒤에서 왜 자리를 못 채우나' "tmp/d27_${tag}.log"
  grep -A 8 '군대가 무너지는 사건' "tmp/d27_${tag}.log"
  grep -A 10 '무엇이 소환수를 죽였나' "tmp/d27_${tag}.log"
done
