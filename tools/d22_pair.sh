#!/usr/bin/env bash
# ── D-22b ㉡ · 「−4.6%」가 손잡이가 낸 것인지 **짝지어** 다시 잰다 ────────────
#
# 앞서 잰 잡음 폭(tools/d22_noise.sh)은 씨앗 무리를 바꾸니 20분 층이
# 68 · 65.83 · 61.33 으로 **6.67층(10.2%)** 벌어졌다 — 문턱 5% 의 두 배다.
# 곧 «무리끼리 견주는 자»로는 −4.6% 를 절대 못 읽는다.
#
# 그런데 D-22b 의 표는 무리끼리 견준 것이 아니라 **같은 씨앗 여섯(무리 A)** 위에서
# 손잡이만 바꾼 것이다 — 씨앗 몫이 양팔에 똑같이 실리므로 상당 부분 상쇄된다.
# 그러니 물어야 할 것은 「잡음이 몇이냐」가 아니라 **「그 짝지은 차이가 다른
# 씨앗 무리에서도 되풀이되느냐」** 다.
#
#   무리 A : 65.83(0) → 62.83(0.03)  = −3.00  ← 이미 있다
#   무리 B : 68.00(0) → ?                        ← 여기서 잰다
#   무리 C : 61.33(0) → ?                        ← 여기서 잰다
#
# 세 차이가 방향과 크기에서 모이면 −4.6% 는 진짜다(㉡ 이 정말 먼저 운다).
# 흩어지면 그 수는 씨앗이 낸 것이고, 씨앗을 크게 늘려야 한다.
. "$(dirname "$0")/ab_guard.sh"
set -u
cd "$(dirname "$0")/.."
node tools/chrome_guard.mjs >/dev/null 2>&1 || true

run() {  # run <이름> <씨앗들>
  echo "── 무리 $1 · 씨앗 $2 · 20분 · __GATE_MIN=0.03 ──"
  NECRO_KNOBS="__GATE_MIN=0.03" node tools/start_probe.mjs 20 "$2" > "tmp/d22p_$1.log" 2>&1
  echo "  끝 · $(wc -l < "tmp/d22p_$1.log") 줄"
}
run B 2,4,6,8,10,12
run C 5,15,17,19,21,23

top() { awk '$1=="1200"{print $2}' "$1" | tail -1; }
echo
echo "════ 짝지은 차이 · 20분(1200초) 층 ════"
printf "  무리 A : 65.83 → 62.83\n"
for g in B C; do
  b=$(top "tmp/d22n_$g.log"); a=$(top "tmp/d22p_$g.log")
  printf "  무리 %s : %s → %s\n" "$g" "$b" "$a"
done
