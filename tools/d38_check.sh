#!/bin/bash
# ★ 긴 측정은 저절로 떨어져 나간다(600초 상한에 잘리지 않게) — tools/ab_guard.sh
. "$(dirname "$0")/ab_guard.sh"
# ══ D-38 · **잦기를 더 밀고, 깊이는 되레 «얕게»** ══ (`__PULSECAP`/`__PULSEON`/`__PULSEOFF`)
#
#   D-37 이 여덟 갈래 만에 처음으로 뒤 사건을 **«늘렸다»**(A 2.33 → P11 2.83 · 1.21배).
#   축과 결은 맞는데 **눈금만 짧다**(문턱 1.5배 = 3.50). D-37 이 남긴 읽음은 하나다 —
#   **«깊이»가 아니라 «잦기»가 사건을 만든다.** 자는 「서 있던 최고 → 절반」을 세는데,
#   깊게 누르면 그 «최고» 자체가 같이 내려앉아 다음 떨어짐이 자에 안 걸린다
#   ([[threshold-and-ruler-must-match]]). 실제로 같은 결에서 깊이만 올리자 되레 졌다:
#   **d 0.5 → 2.83 · 0.8 → 1.50 · 1.0 → 1.50**.
#   ☞ 그런데 **깊이 축은 여태 «깊은 쪽»으로만 갔다** — 0.5 보다 얕은 자리는 한 번도 안 쟀다.
#     봉우리가 0.5 위에 있다면 그 아래도 봐야 봉우리인지 안다([[floor-far-from-threshold]]).
#
#   세 팔 (P11 = on1/off1.5/d0.5 를 가운데 두고 **양쪽으로 한 칸씩**)
#     G1  d0.5 · on1   · off0.5   — 틈만 좁힌다(묽기 40% → 67%). 잦기 ↑ · 깊이 그대로
#     G2  d0.5 · on0.5 · off0.5   — 더 짧고 더 잦게(한 번에 0.5초). 잦기 ↑↑
#     G3  d0.3 · on1   · off1.5   — 결은 P11 과 한 글자도 안 다르고 **깊이만 얕게**
#
#   끝 조건 (재기 전에 적는다 · 9분 × 씨앗 1,3,7,11,13,17 · 견줄 팔은 이미 잰 두 개)
#     ★ A 팔(tmp/d37_A6.log · 끔)   : 앞 판당 23.83 · **뒤 판당 2.33** · 뒤 회복초중앙 18.2 ·
#                                     죽음 24 · 9분 최고층 28.67
#     ★ P11 팔(tmp/d37_P11_6.log)   : 앞 판당 23.83 · **뒤 판당 2.83** · 회복초중앙 21.1 ·
#                                     죽음 24 · 최고층 29 · 걸림 208 · 한 번에 1.0초 · 걸린 층 26.1
#     ① **문이 D-37 보다 더 잦게 도는가** — 「잦은눌림(D-37)」 줄에서 셋을 다 볼 것:
#        걸림이 P11 의 **208 보다 많을 것**(G1·G2) · 한 번에 **1.0초 이하** ·
#        걸린 층 평균 **21 이상**(21 미만이면 앞으로 샌 것이다).
#        ★ G3 은 결이 P11 과 같으니 걸림도 208 언저리여야 정상이다 — 크게 다르면 딴 것을 잰 것.
#     ② **뒤에 «사건»이 더 서는가(D 의 물음)** — 뒤(층 21+) 판당이 A 팔 2.33 의 **1.5배 = 3.50 이상.**
#        ★ **2.83 을 넘기만 해서는 못 켠다** — 넘되 3.50 에 못 미치면 「같은 축을 한 칸 더
#          밀었더니 조금 더 왔다」이고, 그때는 ㉯(얕은 잦은 눌림 + D-32 관문이 직접 무는 것)
#          을 겹치거나 **문턱 자체를 켜서 30초 보고 다시 본다**([[play-it-before-measuring-it]]).
#     ③ **회복이 «시간»을 갖는가** — 뒤 칸 회복초중앙이 A 팔 **18.2 보다 길 것.**
#     ④ **앞을 한 톨도 안 건드렸는가** — 앞(층 1-20) 판당이 23.83 의 **1.1배 이내**,
#        죽음이 24 의 **1.1배 이내.** ★ 층 21 아래에서는 통조차 안 도니 **소수점까지 같아야**
#        정상이고, 움직였다면 샌 것이다.
#     ⑤ **판이 더 얕아지지 않았는가** — 9분 최고층이 A 팔 28.67 의 **85% 이상**(24.4).
#   ★ ②③ 이 서고 ④⑤ 가 살아 있는 팔만 기본값 후보다. 하나라도 어긋나면 ☒ 로 닫고
#     무엇이 어떻게 졌는지를 ROADMAP 에 적는다 — **진 것도 답이다**(D-29~37 이 그랬다).
set -u
cd /Users/lbs/source/personal/necro
MIN=${MIN:-9}; SEEDS=${SEEDS:-1,3,7,11,13,17}
node tools/chrome_guard.mjs || true

for arm in G1 G2 G3; do
  OUT="tmp/d38_${arm}.log"
  [ -s "$OUT" ] && { echo "== $OUT 이미 있음 · 건너뜀 =="; continue; }
  case "$arm" in
    G1) K="__PULSECAP=0.5;__PULSEON=1;__PULSEOFF=0.5" ;;
    G2) K="__PULSECAP=0.5;__PULSEON=0.5;__PULSEOFF=0.5" ;;
    G3) K="__PULSECAP=0.3;__PULSEON=1;__PULSEOFF=1.5" ;;
  esac
  echo "═════ $arm ($K) → $OUT · $(date +%H:%M:%S) ═════"
  NECRO_KNOBS="$K" node tools/start_probe.mjs "$MIN" "$SEEDS" > "$OUT" 2>&1
  echo "== $arm 끝 · $(date +%H:%M:%S) ==" >&2
done

echo ""; echo "══════════ 다 잰 뒤 ══════════"
for arm in A6 P11_6; do
  echo ""; echo "═════ (견줄) $arm · tmp/d37_${arm}.log ═════"
  grep -A 8 '절대 자' "tmp/d37_${arm}.log" | tail -3
  grep '잦은눌림(D-37)' "tmp/d37_${arm}.log"
done
for arm in G1 G2 G3; do
  echo ""; echo "═════ $arm (tmp/d38_${arm}.log) ═════"
  grep -A 8 '절대 자' "tmp/d38_${arm}.log" | tail -4
  grep    '잦은눌림(D-37)' "tmp/d38_${arm}.log"
  grep    '죽음 .* 개의 사진' "tmp/d38_${arm}.log"
  awk '/^ *540 /{print "9분끝 층=" $2}' "tmp/d38_${arm}.log" | tail -1
done
