## ★ 우선순위 (이 순서를 지켜라 — 시간이 모자라면 뒤를 버린다)

### 주 목표 ② 스킬 아이콘을 굽고 «격자»로 세운다
스킬은 일곱이다(`hs/main.js` 의 `SKILL_TREES`):
