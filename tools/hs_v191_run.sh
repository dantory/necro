**이미 구워 둔 것을 먼저 써라**(`assets/ui/icon/` 에 열 장이 있다: amp·burn·decrep·ghoul·golem·
nova·offer·raise·wall·weaken). 네가 직접 열어 보고 어울리는지 판단해라. 내 눈짐작으로는
`nova`→시체폭발 · `amp`→저주 · `raise`→소환 자리 가 맞을 것 같지만 **네가 그림을 보고 정해라.**
남는 넷(`spear`·`grade`·`mdmg`·`mhp`)은 **새로 구워야 한다.**

· **반드시 픽셀랩 파이프라인으로 구워라.** 본보기가 `tools/pixellab/icons.py` 에 그대로 있다
  (`create_map_object` 64×64 · 큐에 전부 줄 세우고 → 돌아가며 받는다 · `--out=` 로 스테이징).
  그 파일의 주석에 **실패한 낱말과 그 까닭**이 잔뜩 적혀 있다 — 굽기 전에 읽어라(부정어는 안 듣는다,
  「emblem」은 액자를 부른다, 「wall」은 받침판을 달고 온다 같은 것들).
· ⛔ **`ctx.filter` 로 칠하거나 `fillRect` 로 그려서 때우지 마라. 유니코드 기호(☠ ✦ ◆)도 금지다** —
  매끈한 벡터 글리프와 계단 진 픽셀은 같은 화면에 못 선다(그래서 옛 판에 icons.py 를 만든 것이다).
· **새로 구운 것은 `tmp/` 에 먼저 받아라**(`--out=tmp/v191_icons`). 살아 있는 그림을 바로 덮지 마라.
  받고 나서 **네가 직접 열어 보고** 쓸 만한 것만 `assets/ui/icon/` 으로 옮겨라. 못 쓸 것은
  **옮기지 말고**, 무엇이 왜 안 나왔는지 로드맵에 적어라(다음 판이 그 낱말을 안 되풀이한다).
