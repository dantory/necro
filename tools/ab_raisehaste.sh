SEEDS=${SEEDS:-"1,3,7,9,11,13,2,4,6,8,10,12"}   # d24_base 와 **같은 판**이라야 맞댈 수 있다
HS=${HS:-"0.5 0.8"}

node tools/chrome_guard.mjs 2>&1 | tail -2

