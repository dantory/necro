# ══ D-25 · **뒤에서 손이 안 돈다 — 빈 자리만큼 소환을 빠르게** (core.js __RAISE_HASTE) ══
#
#   D-24 의 기준선이 ㉮ 의 뿌리를 하나로 좁혔다(20분 × 씨앗 열둘 · tmp/d24_base.log):
#     · 층 21-40 막힘쿨 **74%** · 41-60 **63%** · 61+ 47%  ← 끝 조건「절반 넘음」을 21-60 이 넘는다
#     · 같은 자리에서 **마나·시체·자리는 통째로 0** — 자원도 정원도 아니다
#     · 그리고 **세움 ≈ 잃음**(102/100 · 146/140 · 136/126) — 뒤의 군세 0.58~0.65 는
#       채우다 만 자리가 아니라 «들고 나는 것이 같아서 선 자리»다. 상한을 올려도 안 움직인다.
#   → 잠근 문이 쿨 하나이므로 **쿨에만** 손을 댄다. 이미 있는 팔을 켜는 것이지 새 축이 아니다.
#     raiseHasteMul() = max(0.05, 1 - H × 빈자리비율) · 소환 계열에만 곱한다.
#     ⑨ 는 이 팔을 «얕은 층»(죽고 다시 세우는 구간)을 노려 만들었는데, D-24 로 재 보니
#     **정작 뒤가 늘 35~42% 비어 있다** — 만든 자리보다 여기서 더 산다.
#   ★ 꽉 차면 곱이 **정확히 1** 이라 잘 도는 구간은 한 톨도 안 바뀐다(산수로 선다).
#   ★ 두 팔을 잰다 — D-10 에서 p=0.5 와 p=1.0 이 «같은 값»으로 나와 손잡이가 이어지는
#     값이 아니라 **켜짐/꺼짐**이었던 일이 있다([[knob-that-does-nothing]]). 기울기를 본다.
#
#   판정 (재기 전에 적는다 · 견줄 팔은 이미 디스크에 있다: tmp/d24_base.log):
#     ① **문이 열리는가** — 층 21+ 의 막힘쿨% 가 **절반 아래로**(74/63/47 → <50).
#     ② **상태가 사건으로 바뀌는가** — 뒤(21+)의 군세/상한이 **0.70 위로** 오르고,
#        D-23 의 「무너져 있는 시간%」가 준다(21-40 의 41% 가 기준).
#        ★ 무너짐 «횟수»는 되레 늘어야 맞다 — 0.70 에 닿아야 다시 겨눠지기 때문이다.
#     ③ **앞 6분이 안 물러야 한다** — 앞(층 1~20) 죽음이 기준 팔의 ±20% 안.
#        (앞은 마나도 22~24% 로 같이 무니 쿨만 풀면 마나가 곧장 다음 관문이 된다 —
#         앞이 크게 움직이면 그것이 신호다.)
#     ④ **깊은 층이 도로 안전해지면 안 된다** — 최고층 중앙이 기준 팔의 **115% 아래**.
#   ①②를 같이 넘고 ③④가 서면 H 를 RAISE_HASTE_DEF 로 옮긴다. 기본값은 재기 전까지 **0**.
