#!/bin/bash
# ★ 긴 측정은 저절로 떨어져 나간다(600초 상한에 잘리지 않게) — tools/ab_guard.sh
. "$(dirname "$0")/ab_guard.sh"
# ══ D-39 · **두 손을 겹친다 — 무는 손(D-32) 위에 못 세우게 하는 손(D-37)** ══
#
#   D-38 이 아홉 갈래를 닫으며 남긴 읽음은 하나다 —
#   **한 손잡이로는 «무너짐의 총량»을 못 늘린다. 잘게 썰거나 뭉칠 뿐이다**
#   (판당 × 회복초중앙의 곱이 A 42.4 · G1 40.5 · G2 42.5 로 셋이 같은 수 · [[equilibrium-pushes-back]]).
#   그리고 D-32 가 진 까닭도 같은 모양이었다 — **물면 되세움이 그만큼 따라 오른다**
#   (41-60 칸에서 잃음/분 128 → 148 인데 세움/분이 134 → 155 로 같이 올랐다).
#
#   ☞ **그래서 이번엔 손을 둘로 나눈다**(D-38 이 남긴 ㉯):
#     · **무는 손 = D-32**(`__GATEBLAST`) — 관문 수법이 터질 때 서 있는 군세를 직접 문다.
#       잃음 «총량»을 늘리는 유일한 갈래인데, 혼자서는 자리가 비는 즉시 소환이 메웠다.
#     · **못 세우게 하는 손 = D-37 의 P11**(`__PULSECAP=0.5;__PULSEON=1;__PULSEOFF=1.5`) —
#       무너진 직후 **상한 자체가 얕게 흔들려** 그 메움이 느려진다. 혼자서는 물 이빨이 없어
#       1.21배에 그쳤다.
#     두 손이 서로의 진 까닭을 메운다면 총량(판당 × 회복초중앙)이 P11 의 **59.7 을 넘어야** 한다.
#     안 넘으면 「손을 나눠도 평형이 되받는다」가 되고, 그때 D 의 손잡이 갈래는 **통째로 닫힌다.**
#
#   네 팔 (견줄 둘은 이미 잰 것 · 9분 × 씨앗 1,3,7,11,13,17 — D-37/D-38 과 **같은 자**)
#     H0  GATEBLAST 1.0 **혼자**              — 겹침의 값을 읽으려면 무는 손만의 값이 같은 자로 있어야 한다
#     H1  P11 + GATEBLAST 0.5                 — 겹침(약하게 뭄)
#     H2  P11 + GATEBLAST 1.0                 — 겹침(D-32 사다리의 그 크기)
#   ★ D-32 의 값(9분×씨앗 셋 · 20분×씨앗 열둘)은 **다른 자**라 그대로 못 견준다 — H0 을 새로 잰다
#     ([[threshold-and-ruler-must-match]]).
#
#   끝 조건 (재기 전에 적는다)
#     ★ A 팔(tmp/d37_A6.log · 다 끔) : 앞 판당 23.83 · **뒤 판당 2.33** · 뒤 회복초중앙 18.2 ·
#                                      죽음 24 · 9분 최고층 28.67 · **총량(판당×회복) 42.4**
#     ★ P11 팔(tmp/d37_P11_6.log)    : 앞 판당 23.83 · **뒤 판당 2.83** · 회복초중앙 21.1 ·
#                                      죽음 24 · 최고층 29.00 · **총량 59.7** · 걸림 208 · 한 번에 1.0초
#     ① **두 손이 다 도는가** — H1·H2 에서 「잦은눌림(D-37)」 걸림이 **208 언저리**(±15%)이고
#        「관문폭발(D-32)」 터짐·문 마리가 **0 이 아닐 것.** 한쪽이 안 돌면 겹친 것이 아니다.
#        ★ H0 에는 「잦은눌림」 줄이 **아예 없어야** 정상이다(눌림을 안 켰으니).
#     ② **뒤에 «사건»이 서는가(D 의 물음)** — 뒤(층 21+) 판당이 A 팔 2.33 의 **1.5배 = 3.50 이상.**
#     ③ **겹침이 «둘의 합»보다 나은가 — 이 갈래의 진짜 물음.** H1·H2 의 **총량(뒤 판당 × 뒤
#        회복초중앙)이 P11 의 59.7 과 H0 의 총량을 둘 다 넘을 것.** 못 넘으면 손을 나눠도
#        평형이 되받은 것이고, 진 것을 그대로 적는다.
#     ④ **앞을 한 톨도 안 건드렸는가** — 앞(층 1-20) 판당이 23.83 의 **1.1배 이내**,
#        죽음이 24 의 **1.1배 이내.** ★ 눌림은 층 21 아래에서 통조차 안 돈다(아홉 번 확인).
#        관문폭발은 앞에서도 도니 여기서 새면 그건 **D-32 쪽**이다 — H0 을 보면 갈린다.
#     ⑤ **판이 더 얕아지지 않았는가** — 9분 최고층이 A 팔 28.67 의 **85% 이상**(24.4).
#   ★ ②③ 이 서고 ④⑤ 가 살아 있는 팔만 기본값 후보다. 하나라도 어긋나면 ☒ 로 닫고
#     무엇이 어떻게 졌는지를 ROADMAP 에 적는다 — **진 것도 답이다**(D-29~38 이 그랬다).
set -u
cd /Users/lbs/source/personal/necro
MIN=${MIN:-9}; SEEDS=${SEEDS:-1,3,7,11,13,17}
P11="__PULSECAP=0.5;__PULSEON=1;__PULSEOFF=1.5"
node tools/chrome_guard.mjs || true

for arm in H0 H1 H2; do
  OUT="tmp/d39_${arm}.log"
  [ -s "$OUT" ] && { echo "== $OUT 이미 있음 · 건너뜀 =="; continue; }
  case "$arm" in
    H0) K="__GATEBLAST=1.0" ;;
    H1) K="${P11};__GATEBLAST=0.5" ;;
    H2) K="${P11};__GATEBLAST=1.0" ;;
  esac
  echo "═════ $arm ($K) → $OUT · $(date +%H:%M:%S) ═════"
  NECRO_KNOBS="$K" node tools/start_probe.mjs "$MIN" "$SEEDS" > "$OUT" 2>&1
  echo "== $arm 끝 · $(date +%H:%M:%S) ==" >&2
done

echo ""; echo "══════════ 다 잰 뒤 ══════════"
for arm in A6 P11_6; do
  echo ""; echo "═════ (견줄) $arm · tmp/d37_${arm}.log ═════"
  grep -A 8 '절대 자' "tmp/d37_${arm}.log" | tail -3
  grep '잦은눌림(D-37)' "tmp/d37_${arm}.log" | head -1
done
for arm in H0 H1 H2; do
  echo ""; echo "═════ $arm (tmp/d39_${arm}.log) ═════"
  grep -A 8 '절대 자' "tmp/d39_${arm}.log" | tail -4
  grep    '잦은눌림(D-37)' "tmp/d39_${arm}.log" | head -1
  grep    '관문폭발(D-32)' "tmp/d39_${arm}.log" | head -1
  grep    '죽음 .* 개의 사진' "tmp/d39_${arm}.log"
  awk '/^ *540 /{print "9분끝 층=" $2}' "tmp/d39_${arm}.log" | tail -1
done
