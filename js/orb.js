/* ══════════════════════════════════════════════════════════════
   구슬을 **픽셀로 그린다.**
   ──────────────────────────────────────────────────────────────
   CSS 로 만든 구슬은 `border-radius:50%` 라 가장자리에 안티에일리어싱이 먹고,
   `linear-gradient` 라 색이 매끄럽게 흐른다. 그 매끈함 하나가 픽셀 화면에서
   **제일 튄다** — 캐릭터도 아이콘도 글꼴도 계단으로 서 있는데 구슬만 매끄러우니
   거기만 다른 세계다.

   그래서 30x30 캔버스에 **한 픽셀씩** 그려서 화면에 크게 늘린다:
     · 원은 **계단**이다(x²+y² 로 안팎만 가른다. 중간값 없음)
     · 색은 **네 단계뿐**이다. 픽셀아트에 그라디언트는 없다
     · 표면의 빛도 점 몇 개로 찍는다
   ══════════════════════════════════════════════════════════ */

/* ★★ 병수님: "구슬 너비를 넓힌순없나" — **가로로 넓힌다.**
   그런데 30x30 을 CSS 로 가로만 늘리면 **픽셀이 찌그러진다**(가로로 눌린 직사각형
   픽셀). 픽셀아트에서 그건 곧 「해상도가 안 맞는 그림」으로 읽힌다.
   그래서 **캔버스 자체를 넓게 그린다** — 42x30 타원. 화면 배율은 가로세로가 같으니
   픽셀은 여전히 정사각형이고, 구슬만 넓어진다.
   숫자도 한 격자 올린다(18 → 27px). 넓힌 이유가 그것이다. */
const W = 42, H = 30;              // 캔버스 크기(가로가 넓다)
const RX = W / 2, RY = H / 2;      // 타원의 두 반지름
const R = RY;                      // 테 두께를 재는 기준(세로 반지름 = 예전 그대로)
/** 색을 **몇 단계로 자른다.** 픽셀아트가 픽셀아트인 이유의 절반이 이것이다 —
 *  부드럽게 흐르는 색은 아무리 잘 골라도 사진처럼 보인다. */
const RAMP = {
  hp: ["#e05050", "#b02424", "#7a1010", "#3a0606"],
  mp: ["#5a86e8", "#2f4fb8", "#1a2a7a", "#0a1030"],
};
const EMPTY = ["#241c16", "#181210", "#0e0a08"];   // 안 찬 부분(빈 유리)

/** 테는 **「나 · 쇠 + 금 상감」**으로 정해졌다(병수님이 여섯 중 고름).
 *  금을 넓게 바르면 장신구가 되고, 실선 한 줄만 남기면 「쇠에 금을 상감한 것」이 된다 —
 *  채도가 낮아 전장과 눈을 안 다툰다. 나머지 다섯은 rims.html 에서 다시 볼 수 있다. */
export function drawOrb(cv, kind, pct, rim = "b") {
  const g = cv.getContext("2d");
  const ramp = RAMP[kind] || RAMP.hp;
  g.clearRect(0, 0, W, H);
  const fillTop = H - Math.round(pct * H);         // 여기서부터 아래가 채워져 있다

  for (let y = 0; y < H; y++) {
    for (let x = 0; x < W; x++) {
      /* 타원은 **각 축으로 나눈 뒤 재면** 원과 똑같이 다룰 수 있다. */
      const dx = (x - RX + 0.5) / RX, dy = (y - RY + 0.5) / RY;
      const d = Math.sqrt(dx * dx + dy * dy);      // 0(가운데) ~ 1(가장자리)
      if (d > 1) continue;                         // **타원 밖은 안 찍는다** — 이 판정이 계단을 만든다

      let col;
      if (y >= fillTop) {
        /* 찬 곳 — 가운데가 밝고 가장자리로 갈수록 어둡다. **네 단계로 끊는다.** */
        const i = d < 0.42 ? 0 : d < 0.7 ? 1 : d < 0.9 ? 2 : 3;
        col = ramp[i];
      } else {
        const i = d < 0.6 ? 0 : d < 0.88 ? 1 : 2;
        col = EMPTY[i];
      }
      g.fillStyle = col; g.fillRect(x, y, 1, 1);
    }
  }
  /* 표면의 빛 — **점 몇 개로 찍는다.** 번지는 빛은 유리가 아니라 플라스틱이 된다.
     왼쪽 위 한 덩이(반사)와 아래쪽 한 줄(되비침), 그게 전부다. */
  const ox = (W - 30) / 2;                         // 넓어진 만큼 오른쪽으로 민다
  g.fillStyle = "#ffffff";
  g.fillRect(ox + 8, 6, 2, 1); g.fillRect(ox + 7, 7, 3, 1); g.fillRect(ox + 7, 8, 2, 1);
  g.fillStyle = "#ffffff55";
  g.fillRect(ox + 10, 6, 1, 1); g.fillRect(ox + 6, 9, 1, 1); g.fillRect(ox + 9, 9, 1, 1);
  g.fillStyle = "#ffffff2a";
  g.fillRect(ox + 10, 25, 10, 1); g.fillRect(ox + 9, 24, 12, 1);

  RIM[rim] ? RIM[rim](g) : RIM.a(g);
}

/* ══ 테 여섯 갈래 ══ **하나씩 던져서는 못 맞힌다.** 오늘 판을 열두 번 고치는 동안
   좋아졌다 나빠졌다를 왕복했다 — 나란히 놓고 고르는 편이 빠르다.
   전부 **픽셀로** 그린다. CSS 로 두르면 그 테만 다시 매끄러워진다. */

/** 원의 띠를 훑는다 — 반지름 [lo,hi) 안의 픽셀에 색을 준다.
 *  `f(rr, ang, dx, dy)` 가 색을 정한다. null 이면 안 찍는다. */
function band(g, lo, hi, f) {
  for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
    const ux = (x - RX + 0.5) / RX, uy = (y - RY + 0.5) / RY;
    /* **테 두께는 세로 반지름 기준**으로 잰다(rr = 정규화거리 x R). 그래야 예전에
       고른 두께 값(R-3.2 등)이 그대로 살고, 넓힌 쪽만 테가 조금 두꺼워진다 —
       실제 유리알도 넓은 축의 테가 두꺼워 보이니 그쪽이 자연스럽다. */
    const rr = Math.sqrt(ux * ux + uy * uy) * R;
    if (rr >= hi || rr < lo) continue;
    const dx = ux * RX, dy = uy * RY;
    const col = f(rr, Math.atan2(dy, dx), dx, dy);
    if (col) { g.fillStyle = col; g.fillRect(x, y, 1, 1); }
  }
}

const RIM = {
  /* 가 — **금 두 겹.** (앞서 쓰던 것) 위가 밝고 아래가 어두우면 빛이 위에서 온다는 뜻이고,
     그것만으로 테가 둥글게 말려 보인다. 리벳 넷은 점 하나씩. */
  a(g) {
    band(g, R - 2.2, R, (rr, _a, _dx, dy) => {
      const up = dy < -2;
      return rr > R - 1.1 ? (up ? "#8a7448" : "#2a2016") : (up ? "#c8aa6e" : "#4a3a22");
    });
    for (const [rx, ry] of [[RX, 1], [RX, H - 2], [1, RY], [W - 2, RY]]) {
      g.fillStyle = "#e0c890"; g.fillRect(rx - 1, ry, 2, 1);
      g.fillStyle = "#6b5730"; g.fillRect(rx - 1, ry + 1, 2, 1);
    }
  },

  /* 나 — ★ **이것으로 정해졌다.** 무쇠에 금 실선 한 줄. 금을 넓게 바르면 장신구가 되고, 실선 한 줄만
     남기면 「쇠에 금을 상감한 것」이 된다. 채도가 낮아 전장과 안 다툰다. */
  b(g) {
    band(g, R - 3.2, R, (rr, _a, _dx, dy) => {
      if (rr > R - 1) return dy < 0 ? "#3a332a" : "#15110d";
      if (rr > R - 2) return dy < 0 ? "#c8aa6e" : "#6b5730";   // 상감 실선
      return dy < 0 ? "#241e18" : "#0e0b09";
    });
  },

  /* 다 — **뼈.** 네크로멘서의 구슬이 금테일 이유가 없다. 마디를 낸 아이보리 —
     각도마다 어두운 틈을 넣으면 「뼈를 이어 붙인 고리」로 읽힌다. */
  c(g) {
    band(g, R - 3, R, (rr, ang, _dx, dy) => {
      const seg = (ang + Math.PI) / (Math.PI * 2) * 14;        // 열네 마디
      if (seg % 1 < 0.16) return "#4a4438";                    // 마디 사이 틈
      if (rr > R - 1) return dy < 0 ? "#6b6558" : "#3a352c";
      return dy < 0 ? "#d8d2c4" : "#8a8477";
    });
  },

  /* 라 — **두꺼운 금 베벨.** 네 단계로 깎아 두께를 세게 낸다. 화려한 쪽 —
     D2 의 그 묵직한 금테에 제일 가깝다. */
  d(g) {
    const up = ["#f0dca8", "#c8aa6e", "#8a7448", "#4a3a22"];
    const dn = ["#6b5730", "#4a3a22", "#2a2016", "#15100a"];
    band(g, R - 4, R, (rr, _a, _dx, dy) => {
      const i = Math.min(3, Math.floor(R - rr));               // 바깥부터 0,1,2,3
      return (dy < -1 ? up : dn)[i];
    });
  },

  /* 마 — **발톱 넷.** 테는 어두운 쇠로 얇게 두고, 네 방향에만 금 고정쇠를 물린다.
     보석을 물린 반지가 이렇게 생겼다 — 금이 적어도 「박혔다」가 제일 세게 읽힌다. */
  e(g) {
    band(g, R - 1.8, R, (rr, _a, _dx, dy) => (dy < 0 ? "#2f2820" : "#12100c"));
    band(g, R - 4, R, (rr, ang) => {
      const a = ((ang + Math.PI * 2.25) % (Math.PI / 2)) / (Math.PI / 2);
      if (a > 0.14) return null;                               // 네 자리에만
      return rr > R - 1.6 ? "#f0dca8" : rr > R - 2.8 ? "#c8aa6e" : "#8a7448";
    });
  },

  /* 바 — **테를 없앤다.** 어두운 눌림 한 겹만 남긴다. 판이 조용해지고 구슬이
     알맹이로만 보인다 — 장식을 걷는 쪽이 옳을 때도 있다. */
  f(g) {
    band(g, R - 1.6, R, (rr) => (rr > R - 0.8 ? "#00000099" : "#00000055"));
  },
};
