/* ══════════════════════════════════════════════════════════════
   체력·마나 **구슬**을 픽셀로 그린다.
   ──────────────────────────────────────────────────────────────
   ★★★ 오늘 이걸 네 번 고쳤다. 병수님: "이렇게 밖에 못만드냐, 체력/마나 UI를".
   왕복한 경로를 남겨 둔다 — **같은 데를 또 돌지 않기 위해서다.**

     원(30격자) → 넓히려고 타원 → "아 이건 좀 아닌듯" → 네모 → "이렇게밖에"

   길을 잘못 든 지점은 **모양이 아니라 해상도**였다. 30x30 격자를 112px 로 늘리면
   한 픽셀이 3.7px 짜리 덩어리가 된다 — 그 안에는 **디테일을 넣을 자리 자체가 없다.**
   유리의 두께도, 테의 깎임도, 액체의 수면도 전부 한두 픽셀로 뭉갠 채 모양만 바꾸며
   돌았다. 격자를 64 로 올리고 배율을 **정수 2배**로 맞추면(64x2 = 128px) 픽셀은
   여전히 또렷하면서 그릴 수 있는 것이 네 배가 된다.

   그리고 모양은 **다시 원으로 돌아왔다.** 디아블로의 그 UI는 둥근 구슬이다 —
   「D2 스타일로」라는 주문에 네모는 애초에 답이 아니었다. 넓히려던 것이 원인이었고,
   넓힐 이유(숫자)는 표기를 줄여서 없앤다(아래 참조).

   구슬이 구슬로 보이는 조건 다섯:
     · **구면 음영** — 빛이 한 점에서 오고, 거기서 멀어질수록 어둡다(평평한 색은 원판)
     · **테두리 어둠** — 가장자리 한 겹이 어두워야 공이 말려 들어간다
     · **수면** — 액체 윗면 한 줄이 밝아야 「담긴 것」이 된다
     · **정반사** — 왼쪽 위 작고 또렷한 흰 점. 번지면 유리가 아니라 플라스틱
     · **되비침** — 아래쪽 초승달 한 줄. 유리 뒷면에서 돌아온 빛
   ══════════════════════════════════════════════════════════ */

const S = 64;                       // 캔버스 한 변(화면에서는 정수 2배 = 128px)
const C = (S - 1) / 2;              // 중심
/* ★ D4 의 구슬 테는 **얇다** — 금테를 두껍게 두르면 그것이 볼거리가 되어 액체와
   다툰다(병수님이 준 화면에서 테는 실선 두어 겹뿐이고, 대신 색 발광이 테를 대신한다). */
const R_OUT = 31.5;                 // 테 바깥
const R_IN = 28.2;                  // 유리 안쪽(여기부터 액체) — 테 두께 3.3
const LX = 22, LY = 19;             // 빛이 오는 자리(왼쪽 위)

/** 색은 **네 단계로 자른다.** 부드럽게 흐르는 색은 아무리 잘 골라도 사진처럼 보인다. */
const RAMP = {
  hp: ["#ff7a6a", "#e03a34", "#a01818", "#5c0a0a"],
  mp: ["#89b6ff", "#3d6fe0", "#1f3aa8", "#0d1450"],
};
const SURF  = { hp: "#ffd0b4", mp: "#cfe2ff" };     // 수면 — 제일 밝은 한 줄
/* ══ V-49 — **빈 유리가 종마다 달라야 한다** ═══════════════════════════════
   여태 빈 유리는 **둘이 한 표를 나눠 썼다**(따뜻한 갈색 하나). 체력 구슬에서는
   그것이 맞다 — 갈색과 붉음은 같은 쪽이라 「피가 빠진 유리」로 읽힌다. 그런데
   **마나 구슬에서는 그 갈색이 파랑의 반대쪽**이라, 반쯤 빈 구슬이 「담긴 것이
   줄어든 그릇」이 아니라 **갈색 공 앞에 파란 웅덩이가 놓인 딴 물건**으로 읽혔다
   (`tmp/v49_mp.png` · 12/43 인 마나 구슬).
   ★ 게다가 **빈 쪽이 찬 쪽보다 밝았다** — 마나 액체의 맨 끝(#0d1450)은 밝기 24.7 인데
     빈 유리의 맨 위는 34.9 다. 즉 마나가 바닥나면 **빈 자리가 눈에 먼저 든다.**
     체력은 같은 자에서 0.76 로 안 넘는다([[pixel-verification-calibration]] — 멀쩡한
     쪽을 양성 표본으로 두고 문턱을 맞췄다. 자는 `tools/v49_orb_ruler.py`).
   ★ 규칙 — **빈 유리는 제 액체와 같은 쪽으로 기울고, 그 액체의 맨 끝보다 어둡다.**
     값을 베껴 적지 말고 이 자로 재서 넣는다. 구슬이 셋째가 생겨도 같은 자를 쓴다
     ([[carry-fixes-forward]]).
   ★ 체력 쪽 값은 **한 톨도 안 바꾼다** — 이미 자를 통과하고, 이 구슬은 병수님이
     네 번 되돌린 자리다. 바꾸는 것은 마나뿐이다.
   ★ `__ORBOLD` 는 자가 **옛 빈 유리(공용 갈색)로 되돌려** 같은 판을 두 번 재는 문이다
     (`__BAROLD`·`__CORPSEOLD`·`__campOld` 와 같은 결). */
const EMPTY_OLD = ["#2a211a", "#1c1512", "#120c0a", "#0a0605"];   // 옛 빈 유리(둘이 같이 썼다)
const EMPTY = {
  hp: ["#2a211a", "#1c1512", "#120c0a", "#0a0605"],   // 붉음과 같은 쪽 — 그대로 둔다
  mp: ["#0f1626", "#0a0f1b", "#060911", "#03050a"],   // 파랑과 같은 쪽 · 액체 맨 끝보다 어둡다
};

export function drawOrb(cv, kind, pct) {
  const g = cv.getContext("2d");
  const ramp = RAMP[kind] || RAMP.hp;
  const empty = globalThis.__ORBOLD ? EMPTY_OLD : (EMPTY[kind] || EMPTY.hp);
  g.clearRect(0, 0, S, S);

  /* 액체 높이는 **유리 안쪽에서만** 잰다. 테까지 채우면 유리가 아니라 색종이다. */
  const top = C - R_IN, bot = C + R_IN;
  const fillTop = bot - pct * (bot - top);

  for (let y = 0; y < S; y++) {
    for (let x = 0; x < S; x++) {
      const dx = x - C, dy = y - C;
      const rr = Math.sqrt(dx * dx + dy * dy);
      if (rr > R_OUT) continue;                     // 원 밖은 안 찍는다 — 이 판정이 계단을 만든다

      if (rr > R_IN) { g.fillStyle = ringColor(rr, dx, dy); g.fillRect(x, y, 1, 1); continue; }

      /* ── 유리 안 ── 빛에서 멀어질수록 어둡다(**구면 음영**). 거리를 반지름으로
         나눠 0~1 로 만들고 네 단계로 끊는다. */
      const dl = Math.hypot(x - LX, y - LY) / (R_IN * 1.55);
      let i = dl < 0.34 ? 0 : dl < 0.62 ? 1 : dl < 0.88 ? 2 : 3;
      /* 가장자리 한 겹은 **무조건 어둡게** — 이 한 겹이 공을 말아 넣는다. */
      if (rr > R_IN - 2.2) i = Math.min(3, i + 1);

      let col;
      if (pct > 0.01 && y >= fillTop - 1 && y < fillTop + 1) {
        col = SURF[kind] || SURF.hp;                // 수면
      } else if (y >= fillTop) {
        col = ramp[i];
      } else {
        col = empty[i];
      }
      g.fillStyle = col; g.fillRect(x, y, 1, 1);
    }
  }

  /* ── 정반사 ── **작고 또렷하게.** 번진 흰빛은 유리가 아니라 플라스틱이 된다. */
  g.fillStyle = "#ffffffcc";
  g.fillRect(LX - 1, LY - 2, 4, 2); g.fillRect(LX - 2, LY, 6, 2); g.fillRect(LX - 1, LY + 2, 4, 1);
  g.fillStyle = "#ffffff55";
  g.fillRect(LX + 3, LY - 1, 2, 3); g.fillRect(LX - 4, LY + 1, 2, 2); g.fillRect(LX, LY + 3, 3, 1);

  /* ── 되비침 ── 아래쪽 **초승달** 한 줄. 유리 뒷면에서 돌아온 빛이다. */
  g.fillStyle = "#ffffff22";
  for (let a = Math.PI * 0.58; a < Math.PI * 0.97; a += 0.03) {
    const r = R_IN - 3.5;
    g.fillRect(Math.round(C + Math.cos(a) * r), Math.round(C + Math.sin(a) * r), 1, 1);
  }
  ringOrnaments(g);
}

/** 테 — **무쇠에 금을 상감한 고리**(병수님이 여섯 중 고른 결). 위가 밝고 아래가
 *  어두우면 빛이 위에서 온다는 뜻이고, 그것만으로 고리가 도톰하게 말려 보인다.
 *  안쪽부터: 그늘 한 겹 → 금 베벨 → 무쇠 → 바깥 어둠. */
function ringColor(rr, dx, dy) {
  const up = (dx * -0.55 + dy * -0.84) > 0;         // 왼쪽 위에서 오는 빛을 받는 쪽인가
  if (rr < R_IN + 0.9) return "#0b0705";            // 유리와 테 사이 그늘
  if (rr < R_IN + 2.2) return up ? "#c8ab72" : "#5f4d2b";   // 금 실선(얇게)
  if (rr < R_OUT - 0.7) return up ? "#332d25" : "#15110e";  // 무쇠
  return "#0a0806";                                  // 바깥 한 겹
}

/** 네 방향의 **리벳** — 「박아 놓은 것」이라는 표시. 점 하나면 티가 안 나고
 *  덩어리면 시끄럽다. 2x2 에 아래 그림자 한 줄이 딱 맞다. */
function ringOrnaments(g) {
  const r = R_IN + 1.6;
  for (const a of [-Math.PI / 2, 0, Math.PI / 2, Math.PI]) {
    const x = Math.round(C + Math.cos(a) * r) - 1, y = Math.round(C + Math.sin(a) * r) - 1;
    g.fillStyle = "#f0dca8"; g.fillRect(x, y, 2, 2);
    g.fillStyle = "#4a3a22"; g.fillRect(x, y + 2, 2, 1);
  }
}
